-- Purpose: Define the raw-layer tables used by the seven processed CSV files.
-- Run after selecting CUSTOMER_ANALYTICS.RAW.

USE DATABASE CUSTOMER_ANALYTICS;
USE SCHEMA RAW;

CREATE TABLE IF NOT EXISTS CUSTOMERS (
    CUSTOMER_ID NUMBER,
    SIGNUP_DATE DATE,
    ACQUISITION_CHANNEL VARCHAR(50),
    ACQUISITION_MONTH VARCHAR(20),
    ACQUISITION_CAMPAIGN_ID VARCHAR(100),
    REGION VARCHAR(50),
    DEVICE_TYPE VARCHAR(20),
    FIRST_ORDER_DATE DATE,
    CUSTOMER_STATUS VARCHAR(20),
    DATE_OF_BIRTH DATE,
    GENDER VARCHAR(20)
);

CREATE TABLE IF NOT EXISTS ORDERS (
    ORDER_ID NUMBER,
    CUSTOMER_ID NUMBER,
    ORDER_DATE DATE,
    PRODUCT_CATEGORY VARCHAR(50),
    QUANTITY NUMBER,
    REVENUE NUMBER(12,2),
    DISCOUNT NUMBER(12,2),
    COST_OF_GOODS NUMBER(12,2),
    SHIPPING_COST NUMBER(12,2),
    DELIVERY_REGION_COST NUMBER(12,2),
    PAYMENT_PROCESSING_FEE NUMBER(12,2),
    ORDER_STATUS VARCHAR(30),
    REFUND_AMOUNT NUMBER(12,2),
    NET_REVENUE NUMBER(12,2),
    GROSS_MARGIN NUMBER(12,2)
);

CREATE TABLE IF NOT EXISTS CUSTOMER_FEATURES (
    CUSTOMER_ID NUMBER,
    ORDER_FREQUENCY NUMBER,
    AVG_ORDER_VALUE NUMBER(12,2),
    AVG_DISCOUNT_RATE NUMBER(12,6),
    DAYS_SINCE_LAST_ORDER NUMBER,
    AVG_INTERPURCHASE_TIME NUMBER(12,2),
    SUBSCRIPTION_TENURE NUMBER(12,2),
    DISCOUNT_DEPENDENCY_RATIO NUMBER(12,6)
);

CREATE TABLE IF NOT EXISTS CUSTOMER_UNIT_ECONOMICS (
    CUSTOMER_ID NUMBER,
    TOTAL_REVENUE NUMBER(14,2),
    TOTAL_DISCOUNT NUMBER(14,2),
    TOTAL_COGS NUMBER(14,2),
    TOTAL_SHIPPING NUMBER(14,2),
    TOTAL_REFUNDS NUMBER(14,2),
    CAC NUMBER(12,2),
    CONTRIBUTION_MARGIN NUMBER(14,2),
    LTV NUMBER(14,2),
    PAYBACK_MONTHS NUMBER(12,2)
);

CREATE TABLE IF NOT EXISTS SUBSCRIPTION_HISTORY (
    SUBSCRIPTION_ID NUMBER,
    CUSTOMER_ID NUMBER,
    SUBSCRIPTION_TIER VARCHAR(30),
    START_DATE DATE,
    END_DATE DATE,
    MONTHLY_FEE NUMBER(12,2),
    CHURN_FLAG NUMBER(1,0),
    CHURN_REASON VARCHAR(50),
    REACTIVATION_FLAG NUMBER(1,0)
);

CREATE TABLE IF NOT EXISTS MARKETING_SPEND (
    MONTH DATE,
    CHANNEL VARCHAR(50),
    REGION VARCHAR(50),
    SPEND_AMOUNT NUMBER(14,2),
    IMPRESSIONS NUMBER,
    CLICKS NUMBER,
    CONVERSIONS NUMBER,
    NEW_CUSTOMERS NUMBER,
    CAMPAIGN_ID VARCHAR(100)
);

CREATE TABLE IF NOT EXISTS DATE_DIM (
    DATE DATE,
    DAY NUMBER,
    WEEK NUMBER,
    MONTH NUMBER,
    QUARTER NUMBER,
    YEAR NUMBER,
    FISCAL_YEAR NUMBER
);

