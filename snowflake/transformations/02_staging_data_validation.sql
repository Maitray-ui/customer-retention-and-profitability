DESCRIBE TABLE CUSTOMER_ANALYTICS.RAW.SUBSCRIPTION_HISTORY;

-- Check primary key, missing values and basic integrity

SELECT
    COUNT(*) AS TOTAL_ROWS,
    COUNT(DISTINCT SUBSCRIPTION_ID) AS UNIQUE_SUBSCRIPTIONS,

    COUNT_IF(SUBSCRIPTION_ID IS NULL) AS NULL_SUBSCRIPTION_ID,
    COUNT_IF(CUSTOMER_ID IS NULL) AS NULL_CUSTOMER_ID,
    COUNT_IF(SUBSCRIPTION_TIER IS NULL) AS NULL_TIER,
    COUNT_IF(START_DATE IS NULL) AS NULL_START_DATE,
    COUNT_IF(END_DATE IS NULL) AS NULL_END_DATE,
    COUNT_IF(MONTHLY_FEE IS NULL) AS NULL_MONTHLY_FEE,
    COUNT_IF(CHURN_FLAG IS NULL) AS NULL_CHURN_FLAG,
    COUNT_IF(CHURN_REASON IS NULL) AS NULL_CHURN_REASON,
    COUNT_IF(REACTIVATION_FLAG IS NULL) AS NULL_REACTIVATION_FLAG

FROM CUSTOMER_ANALYTICS.RAW.SUBSCRIPTION_HISTORY;

-- Validate churn and reactivation flags

SELECT
    COUNT(*) AS TOTAL_RECORDS,

    COUNT_IF(CHURN_FLAG NOT IN (0, 1)) AS INVALID_CHURN_FLAGS,

    COUNT_IF(REACTIVATION_FLAG NOT IN (0, 1))
        AS INVALID_REACTIVATION_FLAGS,

    COUNT_IF(CHURN_FLAG = 1 AND CHURN_REASON IS NULL)
        AS CHURNED_WITHOUT_REASON,

    COUNT_IF(CHURN_FLAG = 0 AND CHURN_REASON IS NOT NULL)
        AS NON_CHURNED_WITH_REASON,

    COUNT_IF(CHURN_FLAG = 1) AS CHURNED_SUBSCRIPTIONS,

    COUNT_IF(CHURN_FLAG = 0) AS NON_CHURNED_SUBSCRIPTIONS,

    COUNT_IF(REACTIVATION_FLAG = 1) AS REACTIVATED_SUBSCRIPTIONS

FROM CUSTOMER_ANALYTICS.RAW.SUBSCRIPTION_HISTORY;


-- Validate subscription dates

SELECT
    COUNT(*) AS TOTAL_RECORDS,

    COUNT_IF(END_DATE < START_DATE)
        AS END_BEFORE_START,

    COUNT_IF(END_DATE = START_DATE)
        AS SAME_START_END_DATE,

    COUNT_IF(START_DATE > DATE '2024-12-31')
        AS START_AFTER_DATASET_END,

    COUNT_IF(END_DATE > DATE '2024-12-31')
        AS END_AFTER_DATASET_END,

    COUNT_IF(MONTHLY_FEE <= 0)
        AS NON_POSITIVE_MONTHLY_FEE

FROM CUSTOMER_ANALYTICS.RAW.SUBSCRIPTION_HISTORY;


-- Customer relationships

SELECT
    COUNT(*) AS TOTAL_SUBSCRIPTIONS,

    COUNT_IF(C.CUSTOMER_ID IS NOT NULL)
        AS MATCHED_CUSTOMERS,

    COUNT_IF(C.CUSTOMER_ID IS NULL)
        AS UNMATCHED_CUSTOMERS

FROM CUSTOMER_ANALYTICS.RAW.SUBSCRIPTION_HISTORY S

LEFT JOIN CUSTOMER_ANALYTICS.RAW.CUSTOMERS C
    ON S.CUSTOMER_ID = C.CUSTOMER_ID;


