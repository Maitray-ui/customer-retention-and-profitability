-- Investigate discount dependency calculation

WITH CUSTOMER_DISCOUNTS AS (
    SELECT
        CUSTOMER_ID,
        COUNT(*) AS TOTAL_ORDERS,

        COUNT_IF(DISCOUNT > 0) AS DISCOUNTED_ORDERS,

        COUNT_IF(DISCOUNT > 0) * 1.0
            / NULLIF(COUNT(*), 0) AS CALCULATED_DISCOUNT_RATIO

    FROM CUSTOMER_ANALYTICS.RAW.ORDERS
    GROUP BY CUSTOMER_ID
)

SELECT
    COUNT(*) AS TOTAL_CUSTOMERS,

    COUNT_IF(
        F.DISCOUNT_DEPENDENCY_RATIO =
        COALESCE(D.CALCULATED_DISCOUNT_RATIO, 0)
    ) AS MATCHING_CUSTOMERS,

    COUNT_IF(
        F.DISCOUNT_DEPENDENCY_RATIO <>
        COALESCE(D.CALCULATED_DISCOUNT_RATIO, 0)
    ) AS MISMATCHING_CUSTOMERS

FROM CUSTOMER_ANALYTICS.RAW.CUSTOMER_FEATURES F

LEFT JOIN CUSTOMER_DISCOUNTS D
    ON F.CUSTOMER_ID = D.CUSTOMER_ID;



-- Compare supplied and calculated discount dependency

WITH CUSTOMER_DISCOUNTS AS (
    SELECT
        CUSTOMER_ID,
        COUNT(*) AS TOTAL_ORDERS,
        COUNT_IF(DISCOUNT > 0) AS DISCOUNTED_ORDERS,

        COUNT_IF(DISCOUNT > 0) * 1.0
            / NULLIF(COUNT(*), 0) AS CALCULATED_RATIO

    FROM CUSTOMER_ANALYTICS.RAW.ORDERS
    GROUP BY CUSTOMER_ID
),

COMPARISON AS (
    SELECT
        F.CUSTOMER_ID,
        F.DISCOUNT_DEPENDENCY_RATIO AS SUPPLIED_RATIO,
        COALESCE(D.CALCULATED_RATIO, 0) AS CALCULATED_RATIO,
        COALESCE(D.TOTAL_ORDERS, 0) AS TOTAL_ORDERS,
        COALESCE(D.DISCOUNTED_ORDERS, 0) AS DISCOUNTED_ORDERS

    FROM CUSTOMER_ANALYTICS.RAW.CUSTOMER_FEATURES F

    LEFT JOIN CUSTOMER_DISCOUNTS D
        ON F.CUSTOMER_ID = D.CUSTOMER_ID
)

SELECT
    SUPPLIED_RATIO,

    CASE
        WHEN CALCULATED_RATIO = 0 THEN 'ZERO'
        WHEN CALCULATED_RATIO = 1 THEN 'ONE'
        ELSE 'BETWEEN ZERO AND ONE'
    END AS CALCULATED_RATIO_GROUP,

    COUNT(*) AS CUSTOMER_COUNT

FROM COMPARISON

GROUP BY
    SUPPLIED_RATIO,
    CALCULATED_RATIO_GROUP

ORDER BY
    SUPPLIED_RATIO,
    CALCULATED_RATIO_GROUP;


