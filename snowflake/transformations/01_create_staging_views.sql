-- Project: Customer Retention & Profitability
-- Source: 02_staging_views.sql
-- Purpose: Create the seven STAGING-layer views from the RAW tables.
-- Run after the RAW tables have been created and loaded.
--
-- These views prepare source data for downstream analytics.
-- Validation and profiling queries are maintained separately in
-- 02_staging_data_validation.sql.

USE DATABASE CUSTOMER_ANALYTICS;


CREATE OR REPLACE VIEW CUSTOMER_ANALYTICS.STAGING.STG_CUSTOMERS AS

SELECT
    CUSTOMER_ID,
    SIGNUP_DATE,
    ACQUISITION_CHANNEL,
    ACQUISITION_MONTH,
    ACQUISITION_CAMPAIGN_ID,
    REGION,
    DEVICE_TYPE,
    FIRST_ORDER_DATE,

    CASE
        WHEN FIRST_ORDER_DATE IS NOT NULL THEN TRUE
        ELSE FALSE
    END AS HAS_PLACED_ORDER,

    CUSTOMER_STATUS,
    DATE_OF_BIRTH,
    GENDER

FROM CUSTOMER_ANALYTICS.RAW.CUSTOMERS;

CREATE OR REPLACE VIEW CUSTOMER_ANALYTICS.STAGING.STG_ORDERS AS

SELECT
    ORDER_ID,
    CUSTOMER_ID,
    ORDER_DATE,

    DATE_TRUNC('MONTH', ORDER_DATE) AS ORDER_MONTH,

    PRODUCT_CATEGORY,
    QUANTITY,

    REVENUE,
    DISCOUNT,
    COST_OF_GOODS,
    SHIPPING_COST,
    DELIVERY_REGION_COST,
    PAYMENT_PROCESSING_FEE,

    ORDER_STATUS,

    CASE
        WHEN ORDER_STATUS = 'Completed' THEN TRUE
        ELSE FALSE
    END AS IS_COMPLETED_ORDER,

    CASE
        WHEN ORDER_STATUS = 'Returned' THEN TRUE
        ELSE FALSE
    END AS IS_RETURNED_ORDER,

    REFUND_AMOUNT,
    NET_REVENUE,
    GROSS_MARGIN,

    (
        NET_REVENUE
        - COST_OF_GOODS
        - SHIPPING_COST
        - DELIVERY_REGION_COST
        - PAYMENT_PROCESSING_FEE
    ) AS ADJUSTED_CONTRIBUTION

FROM CUSTOMER_ANALYTICS.RAW.ORDERS;

CREATE OR REPLACE VIEW CUSTOMER_ANALYTICS.STAGING.STG_CUSTOMER_FEATURES AS
SELECT
    CUSTOMER_ID,
    ORDER_FREQUENCY,
    AVG_ORDER_VALUE,
    AVG_DISCOUNT_RATE,
    DAYS_SINCE_LAST_ORDER,
    AVG_INTERPURCHASE_TIME,
    SUBSCRIPTION_TENURE,
    DISCOUNT_DEPENDENCY_RATIO,

    CASE
        WHEN ORDER_FREQUENCY > 0 THEN TRUE
        ELSE FALSE
    END AS HAS_PURCHASED,

    CASE
        WHEN AVG_DISCOUNT_RATE > 0.20 THEN TRUE
        ELSE FALSE
    END AS IS_HIGH_DISCOUNT_DEPENDENT

FROM CUSTOMER_ANALYTICS.RAW.CUSTOMER_FEATURES;

CREATE OR REPLACE VIEW CUSTOMER_ANALYTICS.STAGING.STG_CUSTOMER_UNIT_ECONOMICS AS

SELECT
    CUSTOMER_ID,
    TOTAL_REVENUE,
    TOTAL_DISCOUNT,
    TOTAL_COGS,
    TOTAL_SHIPPING,
    TOTAL_REFUNDS,
    CAC,
    CONTRIBUTION_MARGIN,
    LTV,
    PAYBACK_MONTHS,

    CASE
        WHEN CONTRIBUTION_MARGIN > 0 THEN TRUE
        ELSE FALSE
    END AS HAS_POSITIVE_CONTRIBUTION,

    CASE
        WHEN PAYBACK_MONTHS = 999 THEN 'NOT_RECOVERED'
        ELSE 'RECOVERED'
    END AS PAYBACK_STATUS

FROM CUSTOMER_ANALYTICS.RAW.CUSTOMER_UNIT_ECONOMICS;

CREATE OR REPLACE VIEW CUSTOMER_ANALYTICS.STAGING.STG_SUBSCRIPTION_HISTORY AS

SELECT
    SUBSCRIPTION_ID,
    CUSTOMER_ID,
    SUBSCRIPTION_TIER,
    START_DATE,
    END_DATE,
    MONTHLY_FEE,
    CHURN_FLAG,

    CASE
        WHEN CHURN_FLAG = 1 THEN TRUE
        ELSE FALSE
    END AS IS_CHURNED,

    CHURN_REASON,
    REACTIVATION_FLAG,

    CASE
        WHEN REACTIVATION_FLAG = 1 THEN TRUE
        ELSE FALSE
    END AS IS_REACTIVATED,

    DATEDIFF('DAY', START_DATE, END_DATE) AS SUBSCRIPTION_DURATION_DAYS

FROM CUSTOMER_ANALYTICS.RAW.SUBSCRIPTION_HISTORY;

CREATE OR REPLACE VIEW CUSTOMER_ANALYTICS.STAGING.STG_MARKETING_SPEND AS
SELECT
    MONTH,
    CHANNEL,
    REGION,
    SPEND_AMOUNT,
    IMPRESSIONS,
    CLICKS,
    CONVERSIONS,
    NEW_CUSTOMERS,
    CAMPAIGN_ID,

    ROUND(CLICKS / NULLIF(IMPRESSIONS, 0), 4) AS CTR,

    ROUND(CONVERSIONS / NULLIF(CLICKS, 0), 4) AS CONVERSION_RATE,

    ROUND(SPEND_AMOUNT / NULLIF(NEW_CUSTOMERS, 0), 2)
        AS MARKETING_COST_PER_NEW_CUSTOMER

FROM CUSTOMER_ANALYTICS.RAW.MARKETING_SPEND;

CREATE OR REPLACE VIEW CUSTOMER_ANALYTICS.STAGING.STG_DATE_DIM AS
SELECT
    DATE,
    DAY,
    WEEK,
    MONTH,
    QUARTER,
    YEAR,
    FISCAL_YEAR
FROM CUSTOMER_ANALYTICS.RAW.DATE_DIM;
