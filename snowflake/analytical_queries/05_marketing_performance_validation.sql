SELECT
    COUNT(*) AS TOTAL_RECORDS,
    COUNT(DISTINCT CHANNEL) AS UNIQUE_CHANNELS,
    COUNT(DISTINCT REGION) AS UNIQUE_REGIONS,
    COUNT(DISTINCT CHANNEL || '-' || REGION) AS UNIQUE_COMBINATIONS
FROM CUSTOMER_ANALYTICS.ANALYTICS.VW_MARKETING_CHANNEL_REGION_PERFORMANCE;

-- Check missing values in calculated metrics

SELECT
    COUNT_IF(CHANNEL IS NULL) AS NULL_CHANNELS,
    COUNT_IF(REGION IS NULL) AS NULL_REGIONS,
    COUNT_IF(TOTAL_SPEND IS NULL) AS NULL_SPEND,
    COUNT_IF(TOTAL_NEW_CUSTOMERS IS NULL) AS NULL_NEW_CUSTOMERS,
    COUNT_IF(CTR IS NULL) AS NULL_CTR,
    COUNT_IF(CONVERSION_RATE IS NULL) AS NULL_CONVERSION_RATE,
    COUNT_IF(COST_PER_NEW_CUSTOMER IS NULL) AS NULL_ACQUISITION_COST
FROM CUSTOMER_ANALYTICS.ANALYTICS.VW_MARKETING_CHANNEL_REGION_PERFORMANCE;

-- Verify monthly record distribution

SELECT
    CHANNEL,
    REGION,
    MONTHLY_RECORDS
FROM CUSTOMER_ANALYTICS.ANALYTICS.VW_MARKETING_CHANNEL_REGION_PERFORMANCE
ORDER BY CHANNEL, REGION;

-- Reconcile aggregated values against the staging table

WITH SOURCE_DATA AS (
    SELECT
        CHANNEL,
        REGION,
        COUNT(*) AS MONTHLY_RECORDS,
        SUM(SPEND_AMOUNT) AS TOTAL_SPEND,
        SUM(IMPRESSIONS) AS TOTAL_IMPRESSIONS,
        SUM(CLICKS) AS TOTAL_CLICKS,
        SUM(CONVERSIONS) AS TOTAL_CONVERSIONS,
        SUM(NEW_CUSTOMERS) AS TOTAL_NEW_CUSTOMERS
    FROM CUSTOMER_ANALYTICS.STAGING.STG_MARKETING_SPEND
    GROUP BY CHANNEL, REGION
)
SELECT
    V.CHANNEL,
    V.REGION,
    V.MONTHLY_RECORDS = S.MONTHLY_RECORDS AS RECORDS_MATCH,
    V.TOTAL_SPEND = ROUND(S.TOTAL_SPEND, 2) AS SPEND_MATCH,
    V.TOTAL_IMPRESSIONS = S.TOTAL_IMPRESSIONS AS IMPRESSIONS_MATCH,
    V.TOTAL_CLICKS = S.TOTAL_CLICKS AS CLICKS_MATCH,
    V.TOTAL_CONVERSIONS = S.TOTAL_CONVERSIONS AS CONVERSIONS_MATCH,
    V.TOTAL_NEW_CUSTOMERS = S.TOTAL_NEW_CUSTOMERS AS CUSTOMERS_MATCH

FROM CUSTOMER_ANALYTICS.ANALYTICS.VW_MARKETING_CHANNEL_REGION_PERFORMANCE V
INNER JOIN SOURCE_DATA S
    ON V.CHANNEL = S.CHANNEL
    AND V.REGION = S.REGION
ORDER BY V.CHANNEL, V.REGION;


