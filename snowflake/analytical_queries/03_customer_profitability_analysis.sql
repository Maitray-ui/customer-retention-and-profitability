-- Normalized profitability metrics


WITH CUSTOMER_RANKING AS (
    SELECT
        CUSTOMER_ID,
        TOTAL_REVENUE,
        TOTAL_DISCOUNT,
        TOTAL_COGS,
        TOTAL_SHIPPING,
        TOTAL_REFUNDS,
        CAC,
        CONTRIBUTION_MARGIN,

        NTILE(5) OVER (
            ORDER BY CONTRIBUTION_MARGIN DESC, CUSTOMER_ID
        ) AS CONTRIBUTION_BUCKET

    FROM CUSTOMER_ANALYTICS.STAGING.STG_CUSTOMER_UNIT_ECONOMICS
)

SELECT
    CONTRIBUTION_BUCKET,

    COUNT(*) AS CUSTOMER_COUNT,

    ROUND(AVG(TOTAL_REVENUE), 2)
        AS AVG_REVENUE_PER_CUSTOMER,

    ROUND(
        SUM(TOTAL_DISCOUNT) * 100.0
        / NULLIF(SUM(TOTAL_REVENUE), 0), 2
    ) AS DISCOUNT_RATE,

    ROUND(
        SUM(TOTAL_COGS) * 100.0
        / NULLIF(SUM(TOTAL_REVENUE), 0), 2
    ) AS COGS_RATE,

    ROUND(
        SUM(TOTAL_SHIPPING) * 100.0
        / NULLIF(SUM(TOTAL_REVENUE), 0), 2
    ) AS SHIPPING_RATE,

    ROUND(
        SUM(TOTAL_REFUNDS) * 100.0
        / NULLIF(SUM(TOTAL_REVENUE), 0), 2
    ) AS REFUND_RATE,

    ROUND(AVG(CAC), 2)
        AS AVG_CAC_PER_CUSTOMER,

    ROUND(
        SUM(CONTRIBUTION_MARGIN) * 100.0
        / NULLIF(SUM(TOTAL_REVENUE), 0), 2
    ) AS CONTRIBUTION_MARGIN_RATE

FROM CUSTOMER_RANKING

GROUP BY CONTRIBUTION_BUCKET

ORDER BY CONTRIBUTION_BUCKET;


-- inspect the view

DESC VIEW CUSTOMER_ANALYTICS.ANALYTICS.VW_CUSTOMER_SEGMENTS;

-- Profitability by RFM segment


SELECT
    S.CUSTOMER_SEGMENT,
    COUNT(*) AS CUSTOMER_COUNT,

    ROUND(AVG(U.TOTAL_REVENUE), 2) AS AVG_REVENUE,
    ROUND(AVG(U.CAC), 2) AS AVG_CAC,

    ROUND(AVG(U.CONTRIBUTION_MARGIN), 2)
        AS AVG_CONTRIBUTION,

    ROUND(SUM(U.CONTRIBUTION_MARGIN), 2)
        AS TOTAL_CONTRIBUTION,

    COUNT_IF(U.CONTRIBUTION_MARGIN < 0)
        AS LOSS_MAKING_CUSTOMERS

FROM CUSTOMER_ANALYTICS.ANALYTICS.VW_CUSTOMER_SEGMENTS S

INNER JOIN CUSTOMER_ANALYTICS.STAGING.STG_CUSTOMER_UNIT_ECONOMICS U
    ON S.CUSTOMER_ID = U.CUSTOMER_ID

GROUP BY S.CUSTOMER_SEGMENT
ORDER BY TOTAL_CONTRIBUTION DESC;


