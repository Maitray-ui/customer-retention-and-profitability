-- Customer Unit Economics Baseline.


SELECT
    COUNT(DISTINCT CUSTOMER_ID) AS TOTAL_CUSTOMERS,

    ROUND(SUM(TOTAL_REVENUE), 2) AS TOTAL_REVENUE,

    ROUND(SUM(TOTAL_DISCOUNT), 2) AS TOTAL_DISCOUNT,

    ROUND(SUM(TOTAL_COGS), 2) AS TOTAL_COGS,

    ROUND(SUM(TOTAL_SHIPPING), 2) AS TOTAL_SHIPPING,

    ROUND(SUM(TOTAL_REFUNDS), 2) AS TOTAL_REFUNDS,

    ROUND(SUM(CAC), 2) AS TOTAL_CAC,

    ROUND(SUM(CONTRIBUTION_MARGIN), 2)
        AS TOTAL_CONTRIBUTION_MARGIN,

    ROUND(AVG(CONTRIBUTION_MARGIN), 2)
        AS AVG_CONTRIBUTION_PER_CUSTOMER,

    ROUND(AVG(LTV), 2) AS AVG_DATASET_LTV

FROM CUSTOMER_ANALYTICS.STAGING.STG_CUSTOMER_UNIT_ECONOMICS;


-- Customer profitability distribution


SELECT
    CASE
        WHEN CONTRIBUTION_MARGIN > 0 THEN 'Profitable'
        WHEN CONTRIBUTION_MARGIN = 0 THEN 'Break-even'
        ELSE 'Loss-making'
    END AS PROFITABILITY_STATUS,

    COUNT(*) AS CUSTOMER_COUNT,

    ROUND(
        COUNT(*) * 100.0 / SUM(COUNT(*)) OVER (),
        2
    ) AS CUSTOMER_PERCENTAGE,

    ROUND(
        AVG(CONTRIBUTION_MARGIN),
        2
    ) AS AVG_CONTRIBUTION,

    ROUND(
        SUM(CONTRIBUTION_MARGIN),
        2
    ) AS TOTAL_CONTRIBUTION

FROM CUSTOMER_ANALYTICS.STAGING.STG_CUSTOMER_UNIT_ECONOMICS

GROUP BY PROFITABILITY_STATUS

ORDER BY
    CASE PROFITABILITY_STATUS
        WHEN 'Profitable' THEN 1
        WHEN 'Break-even' THEN 2
        WHEN 'Loss-making' THEN 3
    END;

-- Contribution concentration across customers


WITH CUSTOMER_RANKING AS (
    SELECT
        CUSTOMER_ID,
        TOTAL_REVENUE,
        CONTRIBUTION_MARGIN,

        NTILE(5) OVER (
            ORDER BY CONTRIBUTION_MARGIN DESC, CUSTOMER_ID
        ) AS CONTRIBUTION_BUCKET

    FROM CUSTOMER_ANALYTICS.STAGING.STG_CUSTOMER_UNIT_ECONOMICS
)

SELECT
    CONTRIBUTION_BUCKET,

    COUNT(*) AS CUSTOMER_COUNT,

    ROUND(AVG(CONTRIBUTION_MARGIN), 2)
        AS AVG_CONTRIBUTION,

    ROUND(SUM(TOTAL_REVENUE), 2)
        AS TOTAL_REVENUE,

    ROUND(SUM(CONTRIBUTION_MARGIN), 2)
        AS TOTAL_CONTRIBUTION,

    ROUND(
        SUM(CONTRIBUTION_MARGIN) * 100.0 /
        SUM(SUM(CONTRIBUTION_MARGIN)) OVER (),
        2
    ) AS CONTRIBUTION_SHARE_PERCENTAGE

FROM CUSTOMER_RANKING

GROUP BY CONTRIBUTION_BUCKET

ORDER BY CONTRIBUTION_BUCKET;


