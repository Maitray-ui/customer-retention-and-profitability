-- Subscription churn, discount dependency, and customer lifetime value analysis
-- Source: 03_analytical_views.sql
-- Organized for the Customer Retention & Profitability project.

-- Subscription churn analysis
-- Business question: How many subscribers are churning, why are they leaving, and which subscription tiers experience the most churn?


SELECT
    SUBSCRIPTION_TIER,

    COUNT(*) AS TOTAL_SUBSCRIPTIONS,

    COUNT_IF(CHURN_FLAG = 1) AS CHURNED_SUBSCRIPTIONS,

    ROUND(
        COUNT_IF(CHURN_FLAG = 1) * 100.0 / COUNT(*),
        2
    ) AS CHURN_RATE,

    COUNT_IF(REACTIVATION_FLAG = 1) AS REACTIVATED_SUBSCRIPTIONS

FROM CUSTOMER_ANALYTICS.STAGING.STG_SUBSCRIPTION_HISTORY

GROUP BY SUBSCRIPTION_TIER
ORDER BY TOTAL_SUBSCRIPTIONS DESC;


-- Why are customers churning?
-- Churn reasons by subscription tier


SELECT
    SUBSCRIPTION_TIER,
    CHURN_REASON,

    COUNT(*) AS CHURNED_SUBSCRIPTIONS,

    ROUND(
        COUNT(*) * 100.0 /
        SUM(COUNT(*)) OVER (PARTITION BY SUBSCRIPTION_TIER),
        2
    ) AS REASON_PERCENTAGE

FROM CUSTOMER_ANALYTICS.STAGING.STG_SUBSCRIPTION_HISTORY

WHERE CHURN_FLAG = 1

GROUP BY
    SUBSCRIPTION_TIER,
    CHURN_REASON

ORDER BY
    SUBSCRIPTION_TIER,
    CHURNED_SUBSCRIPTIONS DESC;


-- How long do subscriptions last before churning?
-- Are customers cancelling shortly after subscribing, or are they leaving after several months?


WITH CHURN_TENURE AS (
    SELECT
        SUBSCRIPTION_TIER,
        DATEDIFF('MONTH', START_DATE, END_DATE) AS TENURE_MONTHS
    FROM CUSTOMER_ANALYTICS.STAGING.STG_SUBSCRIPTION_HISTORY
    WHERE CHURN_FLAG = 1
      AND END_DATE IS NOT NULL
)

SELECT
    SUBSCRIPTION_TIER,

    CASE
        WHEN TENURE_MONTHS < 3 THEN '0-2 Months'
        WHEN TENURE_MONTHS < 6 THEN '3-5 Months'
        WHEN TENURE_MONTHS < 12 THEN '6-11 Months'
        ELSE '12+ Months'
    END AS TENURE_GROUP,

    COUNT(*) AS CHURNED_SUBSCRIPTIONS

FROM CHURN_TENURE

GROUP BY SUBSCRIPTION_TIER, TENURE_GROUP

ORDER BY SUBSCRIPTION_TIER, TENURE_GROUP;


-- Validation query: Actual subscription tenure

SELECT
    SUBSCRIPTION_TIER,
    COUNT(*) AS CHURNED_SUBSCRIPTIONS,
    MIN(DATEDIFF('MONTH', START_DATE, END_DATE)) AS MIN_TENURE_MONTHS,
    MAX(DATEDIFF('MONTH', START_DATE, END_DATE)) AS MAX_TENURE_MONTHS,
    ROUND(AVG(DATEDIFF('DAY', START_DATE, END_DATE)), 1)
        AS AVG_TENURE_DAYS
FROM CUSTOMER_ANALYTICS.STAGING.STG_SUBSCRIPTION_HISTORY
WHERE CHURN_FLAG = 1
  AND END_DATE IS NOT NULL
GROUP BY SUBSCRIPTION_TIER;

-- Next: Discount dependency analysis
-- Are customers who depend heavily on discounts actually profitable?

-- Query 1: Profitability of discount-dependent customers


SELECT
    F.IS_HIGH_DISCOUNT_DEPENDENT,

    COUNT(*) AS CUSTOMER_COUNT,

    ROUND(AVG(F.AVG_DISCOUNT_RATE) * 100, 2)
        AS AVG_DISCOUNT_RATE,

    ROUND(AVG(U.TOTAL_REVENUE), 2)
        AS AVG_REVENUE,

    ROUND(AVG(U.CONTRIBUTION_MARGIN), 2)
        AS AVG_CONTRIBUTION,

    ROUND(SUM(U.CONTRIBUTION_MARGIN), 2)
        AS TOTAL_CONTRIBUTION,

    COUNT_IF(U.CONTRIBUTION_MARGIN < 0)
        AS LOSS_MAKING_CUSTOMERS

FROM CUSTOMER_ANALYTICS.STAGING.STG_CUSTOMER_FEATURES F

INNER JOIN CUSTOMER_ANALYTICS.STAGING.STG_CUSTOMER_UNIT_ECONOMICS U
    ON F.CUSTOMER_ID = U.CUSTOMER_ID

GROUP BY F.IS_HIGH_DISCOUNT_DEPENDENT

ORDER BY F.IS_HIGH_DISCOUNT_DEPENDENT;


-- Next: Customer Lifetime Value (CLV)
-- Business question: How is customer value distributed across our customer base?


SELECT
    COUNT(*) AS TOTAL_CUSTOMERS,

    COUNT_IF(LTV > 0) AS POSITIVE_LTV_CUSTOMERS,

    COUNT_IF(LTV = 0) AS ZERO_LTV_CUSTOMERS,

    ROUND(AVG(LTV), 2) AS AVG_LTV,

    ROUND(MEDIAN(LTV), 2) AS MEDIAN_LTV,

    ROUND(MAX(LTV), 2) AS MAX_LTV,

    ROUND(SUM(LTV), 2) AS TOTAL_LTV

FROM CUSTOMER_ANALYTICS.STAGING.STG_CUSTOMER_UNIT_ECONOMICS;


-- How does LTV differ across acquisition channels?
-- Business question: Which acquisition channels bring customers with the highest historical lifetime value?


SELECT
    C.ACQUISITION_CHANNEL,

    COUNT(*) AS CUSTOMER_COUNT,

    ROUND(AVG(U.LTV), 2) AS AVG_LTV,

    ROUND(MEDIAN(U.LTV), 2) AS MEDIAN_LTV,

    ROUND(SUM(U.LTV), 2) AS TOTAL_LTV,

    COUNT_IF(U.LTV = 0) AS ZERO_LTV_CUSTOMERS,

    ROUND(
        COUNT_IF(U.LTV = 0) * 100.0 / COUNT(*), 2
    ) AS ZERO_LTV_PERCENTAGE

FROM CUSTOMER_ANALYTICS.STAGING.STG_CUSTOMERS C

INNER JOIN CUSTOMER_ANALYTICS.STAGING.STG_CUSTOMER_UNIT_ECONOMICS U
    ON C.CUSTOMER_ID = U.CUSTOMER_ID

GROUP BY C.ACQUISITION_CHANNEL

ORDER BY TOTAL_LTV DESC;


-- CLV by customer region

SELECT
    C.REGION,
    COUNT(*) AS CUSTOMER_COUNT,
    ROUND(AVG(U.LTV), 2) AS AVG_LTV,
    ROUND(MEDIAN(U.LTV), 2) AS MEDIAN_LTV,
    ROUND(SUM(U.LTV), 2) AS TOTAL_LTV,
    COUNT_IF(U.LTV = 0) AS ZERO_LTV_CUSTOMERS,
    ROUND(
        COUNT_IF(U.LTV = 0) * 100.0 / COUNT(*),
        2
    ) AS ZERO_LTV_PERCENTAGE
FROM CUSTOMER_ANALYTICS.STAGING.STG_CUSTOMERS C
INNER JOIN CUSTOMER_ANALYTICS.STAGING.STG_CUSTOMER_UNIT_ECONOMICS U
    ON C.CUSTOMER_ID = U.CUSTOMER_ID
GROUP BY C.REGION
ORDER BY TOTAL_LTV DESC;

-- examine payback performance.

SELECT
    C.ACQUISITION_CHANNEL,
    COUNT(*) AS CUSTOMER_COUNT,
    COUNT_IF(U.PAYBACK_MONTHS = 999) AS NOT_RECOVERED_CUSTOMERS,
    ROUND(
        COUNT_IF(U.PAYBACK_MONTHS = 999) * 100.0 / COUNT(*),
        2
    ) AS NOT_RECOVERED_PERCENTAGE,
    ROUND(
        AVG(IFF(U.PAYBACK_MONTHS <> 999, U.PAYBACK_MONTHS, NULL)),
        2
    ) AS AVG_PAYBACK_MONTHS
FROM CUSTOMER_ANALYTICS.STAGING.STG_CUSTOMERS C
INNER JOIN CUSTOMER_ANALYTICS.STAGING.STG_CUSTOMER_UNIT_ECONOMICS U
    ON C.CUSTOMER_ID = U.CUSTOMER_ID
GROUP BY C.ACQUISITION_CHANNEL
ORDER BY NOT_RECOVERED_PERCENTAGE DESC;

-- CLV by acquisition channel and RFM segment
-- Does a particular acquisition channel bring valuable customers across multiple segments, or does its value depend on a small group of high-value customers?

SELECT
    C.ACQUISITION_CHANNEL,
    S.CUSTOMER_SEGMENT,
    COUNT(*) AS CUSTOMER_COUNT,
    ROUND(AVG(U.LTV), 2) AS AVG_LTV,
    ROUND(MEDIAN(U.LTV), 2) AS MEDIAN_LTV,
    ROUND(SUM(U.LTV), 2) AS TOTAL_LTV,
    COUNT_IF(U.LTV = 0) AS ZERO_LTV_CUSTOMERS,
    ROUND(
        COUNT_IF(U.LTV = 0) * 100.0 / COUNT(*),
        2
    ) AS ZERO_LTV_PERCENTAGE
FROM CUSTOMER_ANALYTICS.STAGING.STG_CUSTOMERS C
INNER JOIN CUSTOMER_ANALYTICS.ANALYTICS.VW_CUSTOMER_SEGMENTS S
    ON C.CUSTOMER_ID = S.CUSTOMER_ID
INNER JOIN CUSTOMER_ANALYTICS.STAGING.STG_CUSTOMER_UNIT_ECONOMICS U
    ON C.CUSTOMER_ID = U.CUSTOMER_ID
GROUP BY
    C.ACQUISITION_CHANNEL,
    S.CUSTOMER_SEGMENT
ORDER BY
    C.ACQUISITION_CHANNEL,
    TOTAL_LTV DESC;
