SELECT
    O.ORDER_MONTH,
    YEAR(O.ORDER_MONTH) AS ORDER_YEAR,
    MONTH(O.ORDER_MONTH) AS MONTH_NUMBER,

    C.REGION,
    C.ACQUISITION_CHANNEL,

    COUNT(DISTINCT O.ORDER_ID) AS TOTAL_ORDERS,
    COUNT(DISTINCT O.CUSTOMER_ID) AS UNIQUE_CUSTOMERS,

    ROUND(SUM(O.NET_REVENUE), 2) AS NET_REVENUE,

    ROUND(SUM(O.ADJUSTED_CONTRIBUTION), 2)
        AS TOTAL_CONTRIBUTION,

    ROUND(
        SUM(O.ADJUSTED_CONTRIBUTION) * 100.0 /
        NULLIF(SUM(O.NET_REVENUE), 0), 2
    ) AS CONTRIBUTION_MARGIN_RATE

FROM CUSTOMER_ANALYTICS.STAGING.STG_ORDERS O

LEFT JOIN CUSTOMER_ANALYTICS.STAGING.STG_CUSTOMERS C
    ON O.CUSTOMER_ID = C.CUSTOMER_ID

WHERE O.IS_COMPLETED_ORDER = TRUE

GROUP BY
    O.ORDER_MONTH,
    YEAR(O.ORDER_MONTH),
    MONTH(O.ORDER_MONTH),
    C.REGION,
    C.ACQUISITION_CHANNEL;


