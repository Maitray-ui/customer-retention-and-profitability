CREATE OR REPLACE TABLE CUSTOMER_ANALYTICS.ANALYTICS.CUSTOMER_SEGMENTS AS

WITH CUSTOMER_RFM AS (
    SELECT
        CUSTOMER_ID,

        DATEDIFF(
            DAY,
            MAX(ORDER_DATE),
            '2024-12-31'::DATE
        ) AS RECENCY_DAYS,

        COUNT(DISTINCT ORDER_ID) AS FREQUENCY,

        SUM(NET_REVENUE) AS MONETARY,

        SUM(ADJUSTED_CONTRIBUTION) AS TOTAL_CONTRIBUTION

    FROM CUSTOMER_ANALYTICS.STAGING.STG_ORDERS

    WHERE IS_COMPLETED_ORDER = TRUE
      AND ORDER_DATE <= '2024-12-31'

    GROUP BY CUSTOMER_ID
),

RFM_SCORES AS (
    SELECT
        *,

        NTILE(5) OVER (
            ORDER BY RECENCY_DAYS DESC
        ) AS R_SCORE,

        NTILE(5) OVER (
            ORDER BY FREQUENCY ASC
        ) AS F_SCORE,

        NTILE(5) OVER (
            ORDER BY MONETARY ASC
        ) AS M_SCORE

    FROM CUSTOMER_RFM
),

SEGMENTED_CUSTOMERS AS (
    SELECT
        *,
        R_SCORE + F_SCORE + M_SCORE AS RFM_SCORE,

        CASE
            WHEN R_SCORE + F_SCORE + M_SCORE >= 13
                THEN 'Champions'

            WHEN R_SCORE + F_SCORE + M_SCORE >= 10
                THEN 'Loyal Customers'

            WHEN R_SCORE + F_SCORE + M_SCORE >= 8
                THEN 'Potential Loyalists'

            WHEN R_SCORE + F_SCORE + M_SCORE >= 5
                THEN 'At Risk'

            ELSE 'Hibernating'
        END AS CUSTOMER_SEGMENT

    FROM RFM_SCORES
)

SELECT
    '2024-12-31'::DATE AS SNAPSHOT_DATE,

    S.CUSTOMER_SEGMENT,
    C.REGION,
    C.ACQUISITION_CHANNEL,

    COUNT(DISTINCT S.CUSTOMER_ID) AS CUSTOMER_COUNT,

    SUM(S.FREQUENCY) AS TOTAL_ORDERS,

    SUM(S.MONETARY) AS TOTAL_REVENUE,

    SUM(S.TOTAL_CONTRIBUTION) AS TOTAL_CONTRIBUTION,

    AVG(S.RECENCY_DAYS) AS AVG_RECENCY_DAYS,

    AVG(S.FREQUENCY) AS AVG_FREQUENCY,

    AVG(S.MONETARY) AS AVG_MONETARY_VALUE,

    AVG(S.TOTAL_CONTRIBUTION) AS AVG_CONTRIBUTION_PER_CUSTOMER,

    COUNT_IF(S.TOTAL_CONTRIBUTION > 0)
        AS PROFITABLE_CUSTOMER_COUNT,

    SUM(S.TOTAL_CONTRIBUTION)
        / NULLIF(SUM(S.MONETARY), 0) * 100
        AS CONTRIBUTION_MARGIN_RATE

FROM SEGMENTED_CUSTOMERS S

LEFT JOIN CUSTOMER_ANALYTICS.STAGING.STG_CUSTOMERS C
    ON S.CUSTOMER_ID = C.CUSTOMER_ID

GROUP BY
    S.CUSTOMER_SEGMENT,
    C.REGION,
    C.ACQUISITION_CHANNEL;


CREATE OR REPLACE TABLE CUSTOMER_ANALYTICS.ANALYTICS.COHORT_RETENTION AS

WITH COMPLETED_ORDERS AS (
    SELECT
        ORDER_ID,
        CUSTOMER_ID,
        ORDER_MONTH,
        NET_REVENUE,
        ADJUSTED_CONTRIBUTION
    FROM CUSTOMER_ANALYTICS.STAGING.STG_ORDERS
    WHERE IS_COMPLETED_ORDER = TRUE
      AND ORDER_DATE <= '2024-12-31'
),

CUSTOMER_COHORTS AS (
    SELECT
        CUSTOMER_ID,
        MIN(ORDER_MONTH) AS COHORT_MONTH
    FROM COMPLETED_ORDERS
    GROUP BY CUSTOMER_ID
),

COHORT_MEMBERS AS (
    SELECT
        CC.CUSTOMER_ID,
        CC.COHORT_MONTH,
        C.REGION,
        C.ACQUISITION_CHANNEL
    FROM CUSTOMER_COHORTS CC
    LEFT JOIN CUSTOMER_ANALYTICS.STAGING.STG_CUSTOMERS C
        ON CC.CUSTOMER_ID = C.CUSTOMER_ID
),

COHORT_SIZES AS (
    SELECT
        COHORT_MONTH,
        REGION,
        ACQUISITION_CHANNEL,
        COUNT(DISTINCT CUSTOMER_ID) AS COHORT_SIZE
    FROM COHORT_MEMBERS
    GROUP BY
        COHORT_MONTH,
        REGION,
        ACQUISITION_CHANNEL
),

MONTHLY_ACTIVITY AS (
    SELECT
        CUSTOMER_ID,
        ORDER_MONTH,
        SUM(NET_REVENUE) AS MONTHLY_REVENUE,
        SUM(ADJUSTED_CONTRIBUTION) AS MONTHLY_CONTRIBUTION
    FROM COMPLETED_ORDERS
    GROUP BY CUSTOMER_ID, ORDER_MONTH
),

COHORT_AGES AS (
    SELECT
        SEQ4() AS COHORT_AGE
    FROM TABLE(GENERATOR(ROWCOUNT => 48))
),

COHORT_GRID AS (
    SELECT
        CS.COHORT_MONTH,
        CS.REGION,
        CS.ACQUISITION_CHANNEL,
        CS.COHORT_SIZE,
        CA.COHORT_AGE,
        DATEADD(
            MONTH,
            CA.COHORT_AGE,
            CS.COHORT_MONTH
        ) AS ACTIVITY_MONTH
    FROM COHORT_SIZES CS
    CROSS JOIN COHORT_AGES CA
    WHERE DATEADD(
        MONTH,
        CA.COHORT_AGE,
        CS.COHORT_MONTH
    ) <= '2024-12-01'::DATE
)

SELECT
    G.COHORT_MONTH,
    G.COHORT_AGE,
    G.REGION,
    G.ACQUISITION_CHANNEL,
    G.COHORT_SIZE,

    COUNT(DISTINCT A.CUSTOMER_ID) AS ACTIVE_CUSTOMERS,

    ROUND(
        COUNT(DISTINCT A.CUSTOMER_ID)
        / NULLIF(G.COHORT_SIZE, 0) * 100,
        2
    ) AS RETENTION_RATE,

    ROUND(COALESCE(SUM(A.MONTHLY_REVENUE), 0), 2)
        AS RETAINED_REVENUE,

    ROUND(COALESCE(SUM(A.MONTHLY_CONTRIBUTION), 0), 2)
        AS RETAINED_CONTRIBUTION

FROM COHORT_GRID G

JOIN COHORT_MEMBERS M
    ON G.COHORT_MONTH = M.COHORT_MONTH
   AND EQUAL_NULL(G.REGION, M.REGION)
   AND EQUAL_NULL(G.ACQUISITION_CHANNEL, M.ACQUISITION_CHANNEL)

LEFT JOIN MONTHLY_ACTIVITY A
    ON M.CUSTOMER_ID = A.CUSTOMER_ID
   AND G.ACTIVITY_MONTH = A.ORDER_MONTH

GROUP BY
    G.COHORT_MONTH,
    G.COHORT_AGE,
    G.REGION,
    G.ACQUISITION_CHANNEL,
    G.COHORT_SIZE;


CREATE OR REPLACE TABLE CUSTOMER_ANALYTICS.ANALYTICS.ACQUISITION_PERFORMANCE AS

WITH CUSTOMER_ACQUISITION AS (
    SELECT
        CUSTOMER_ID,
        DATE_TRUNC('MONTH', SIGNUP_DATE)::DATE AS ACQUISITION_MONTH,
        REGION,
        ACQUISITION_CHANNEL
    FROM CUSTOMER_ANALYTICS.STAGING.STG_CUSTOMERS
    WHERE SIGNUP_DATE IS NOT NULL
      AND SIGNUP_DATE <= '2024-12-31'
),

CUSTOMER_METRICS AS (
    SELECT
        CUSTOMER_ID,
        CAC,
        TOTAL_REVENUE,
        CONTRIBUTION_MARGIN
    FROM CUSTOMER_ANALYTICS.STAGING.STG_CUSTOMER_UNIT_ECONOMICS
),

ORDER_ACTIVITY AS (
    SELECT
        CUSTOMER_ID,
        COUNT(DISTINCT ORDER_ID) AS COMPLETED_ORDERS
    FROM CUSTOMER_ANALYTICS.STAGING.STG_ORDERS
    WHERE IS_COMPLETED_ORDER = TRUE
      AND ORDER_DATE <= '2024-12-31'
    GROUP BY CUSTOMER_ID
)

SELECT
    A.ACQUISITION_MONTH,
    A.REGION,
    A.ACQUISITION_CHANNEL,

    COUNT(DISTINCT A.CUSTOMER_ID) AS NEW_CUSTOMERS,

    ROUND(SUM(COALESCE(M.CAC, 0)), 2) AS ACQUISITION_SPEND,

    ROUND(
        SUM(COALESCE(M.CAC, 0))
        / NULLIF(COUNT(DISTINCT A.CUSTOMER_ID), 0),
        2
    ) AS AVG_CAC,

    COUNT(DISTINCT CASE
        WHEN O.COMPLETED_ORDERS > 0 THEN A.CUSTOMER_ID
    END) AS FIRST_ORDER_CUSTOMERS,

    ROUND(SUM(COALESCE(M.TOTAL_REVENUE, 0)), 2)
        AS TOTAL_REVENUE,

    ROUND(SUM(COALESCE(M.CONTRIBUTION_MARGIN, 0)), 2)
        AS TOTAL_CONTRIBUTION

FROM CUSTOMER_ACQUISITION A

LEFT JOIN CUSTOMER_METRICS M
    ON A.CUSTOMER_ID = M.CUSTOMER_ID

LEFT JOIN ORDER_ACTIVITY O
    ON A.CUSTOMER_ID = O.CUSTOMER_ID

GROUP BY
    A.ACQUISITION_MONTH,
    A.REGION,
    A.ACQUISITION_CHANNEL;


CREATE OR REPLACE TABLE CUSTOMER_ANALYTICS.ANALYTICS.CUSTOMER_LTV AS

WITH CUSTOMER_RFM AS (
    SELECT
        CUSTOMER_ID,
        DATEDIFF(DAY, MAX(ORDER_DATE), '2024-12-31'::DATE)
            AS RECENCY_DAYS,
        COUNT(DISTINCT ORDER_ID) AS FREQUENCY,
        SUM(NET_REVENUE) AS MONETARY
    FROM CUSTOMER_ANALYTICS.STAGING.STG_ORDERS
    WHERE IS_COMPLETED_ORDER = TRUE
      AND ORDER_DATE <= '2024-12-31'
    GROUP BY CUSTOMER_ID
),

RFM_SCORES AS (
    SELECT
        *,
        NTILE(5) OVER (ORDER BY RECENCY_DAYS DESC) AS R_SCORE,
        NTILE(5) OVER (ORDER BY FREQUENCY ASC) AS F_SCORE,
        NTILE(5) OVER (ORDER BY MONETARY ASC) AS M_SCORE
    FROM CUSTOMER_RFM
),

CUSTOMER_SEGMENTS AS (
    SELECT
        CUSTOMER_ID,
        CASE
            WHEN R_SCORE + F_SCORE + M_SCORE >= 13
                THEN 'Champions'
            WHEN R_SCORE + F_SCORE + M_SCORE >= 10
                THEN 'Loyal Customers'
            WHEN R_SCORE + F_SCORE + M_SCORE >= 8
                THEN 'Potential Loyalists'
            WHEN R_SCORE + F_SCORE + M_SCORE >= 5
                THEN 'At Risk'
            ELSE 'Hibernating'
        END AS CUSTOMER_SEGMENT
    FROM RFM_SCORES
),

CUSTOMER_ECONOMICS AS (
    SELECT
        CUSTOMER_ID,
        LTV,
        CAC,
        CONTRIBUTION_MARGIN,
        PAYBACK_MONTHS,
        HAS_POSITIVE_CONTRIBUTION
    FROM CUSTOMER_ANALYTICS.STAGING.STG_CUSTOMER_UNIT_ECONOMICS
)

SELECT
    '2024-12-31'::DATE AS SNAPSHOT_DATE,
    S.CUSTOMER_SEGMENT,
    C.REGION,
    C.ACQUISITION_CHANNEL,

    COUNT(DISTINCT S.CUSTOMER_ID) AS CUSTOMER_COUNT,

    ROUND(SUM(E.LTV), 2) AS TOTAL_LTV,
    ROUND(AVG(E.LTV), 2) AS AVG_LTV,

    ROUND(SUM(E.CAC), 2) AS TOTAL_CAC,
    ROUND(AVG(E.CAC), 2) AS AVG_CAC,

    ROUND(SUM(E.CONTRIBUTION_MARGIN), 2)
        AS TOTAL_CONTRIBUTION,

    ROUND(AVG(E.CONTRIBUTION_MARGIN), 2)
        AS AVG_CONTRIBUTION,

    ROUND(
        SUM(E.LTV) / NULLIF(SUM(E.CAC), 0),
        2
    ) AS LTV_CAC_RATIO,

    COUNT_IF(E.HAS_POSITIVE_CONTRIBUTION = TRUE)
        AS PROFITABLE_CUSTOMERS,

    ROUND(AVG(E.PAYBACK_MONTHS), 2)
        AS AVG_PAYBACK_MONTHS

FROM CUSTOMER_SEGMENTS S

JOIN CUSTOMER_ANALYTICS.STAGING.STG_CUSTOMERS C
    ON S.CUSTOMER_ID = C.CUSTOMER_ID

LEFT JOIN CUSTOMER_ECONOMICS E
    ON S.CUSTOMER_ID = E.CUSTOMER_ID

GROUP BY
    S.CUSTOMER_SEGMENT,
    C.REGION,
    C.ACQUISITION_CHANNEL;


CREATE OR REPLACE TABLE CUSTOMER_ANALYTICS.ANALYTICS.SUBSCRIPTION_CHURN AS

WITH SUBSCRIPTION_DATA AS (
    SELECT
        S.SUBSCRIPTION_ID,
        S.CUSTOMER_ID,
        DATE_TRUNC('MONTH', S.END_DATE)::DATE AS CHURN_MONTH,
        S.SUBSCRIPTION_TIER,
        S.MONTHLY_FEE,
        S.IS_CHURNED,
        S.CHURN_REASON,
        S.IS_REACTIVATED,
        S.SUBSCRIPTION_DURATION_DAYS,
        C.REGION

    FROM CUSTOMER_ANALYTICS.STAGING.STG_SUBSCRIPTION_HISTORY S

    LEFT JOIN CUSTOMER_ANALYTICS.STAGING.STG_CUSTOMERS C
        ON S.CUSTOMER_ID = C.CUSTOMER_ID

    WHERE S.END_DATE IS NOT NULL
      AND S.END_DATE <= '2024-12-31'
)

SELECT
    CHURN_MONTH,
    REGION,
    SUBSCRIPTION_TIER,

    COUNT(DISTINCT SUBSCRIPTION_ID)
        AS TOTAL_SUBSCRIPTIONS_ENDED,

    COUNT(DISTINCT CASE
        WHEN IS_CHURNED = TRUE THEN SUBSCRIPTION_ID
    END) AS CHURNED_SUBSCRIPTIONS,

    COUNT(DISTINCT CUSTOMER_ID)
        AS TOTAL_CUSTOMERS,

    COUNT(DISTINCT CASE
        WHEN IS_CHURNED = TRUE THEN CUSTOMER_ID
    END) AS CHURNED_CUSTOMERS,

    COUNT(DISTINCT CASE
        WHEN IS_REACTIVATED = TRUE THEN SUBSCRIPTION_ID
    END) AS REACTIVATED_SUBSCRIPTIONS,

    ROUND(
        COUNT(DISTINCT CASE
            WHEN IS_CHURNED = TRUE THEN SUBSCRIPTION_ID
        END)
        / NULLIF(COUNT(DISTINCT SUBSCRIPTION_ID), 0) * 100,
        2
    ) AS CHURN_RATE,

    ROUND(
        AVG(SUBSCRIPTION_DURATION_DAYS),
        2
    ) AS AVG_SUBSCRIPTION_DURATION_DAYS,

    ROUND(
        SUM(CASE
            WHEN IS_CHURNED = TRUE THEN MONTHLY_FEE
            ELSE 0
        END),
        2
    ) AS LOST_MONTHLY_REVENUE

FROM SUBSCRIPTION_DATA

GROUP BY
    CHURN_MONTH,
    REGION,
    SUBSCRIPTION_TIER;
