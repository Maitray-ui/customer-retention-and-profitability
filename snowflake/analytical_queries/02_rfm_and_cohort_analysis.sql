-- RFM validation, customer segmentation, and cohort retention analysis
-- Source: 03_analytical_views.sql
-- Organized for the Customer Retention & Profitability project.

-- validate

SELECT
    COUNT(*) AS TOTAL_CUSTOMERS,
    COUNT(DISTINCT CUSTOMER_ID) AS UNIQUE_CUSTOMERS,
    COUNT_IF(RECENCY < 0) AS INVALID_RECENCY,
    COUNT_IF(FREQUENCY <= 0) AS INVALID_FREQUENCY,
    COUNT_IF(MONETARY IS NULL) AS NULL_MONETARY,
    MIN(RECENCY) AS MIN_RECENCY,
    MAX(RECENCY) AS MAX_RECENCY,
    AVG(RECENCY) AS AVG_RECENCY,
    AVG(FREQUENCY) AS AVG_FREQUENCY,
    AVG(MONETARY) AS AVG_MONETARY
FROM CUSTOMER_ANALYTICS.ANALYTICS.VW_RFM_BASE;


-- Validate the scores

SELECT
    COUNT(*) AS TOTAL_CUSTOMERS,

    MIN(R_SCORE) AS MIN_R_SCORE,
    MAX(R_SCORE) AS MAX_R_SCORE,

    MIN(F_SCORE) AS MIN_F_SCORE,
    MAX(F_SCORE) AS MAX_F_SCORE,

    MIN(M_SCORE) AS MIN_M_SCORE,
    MAX(M_SCORE) AS MAX_M_SCORE,

    AVG(R_SCORE) AS AVG_R_SCORE,
    AVG(F_SCORE) AS AVG_F_SCORE,
    AVG(M_SCORE) AS AVG_M_SCORE

FROM CUSTOMER_ANALYTICS.ANALYTICS.VW_RFM_SCORES;

-- Inspect the score distribution

SELECT
    'RECENCY' AS METRIC,
    R_SCORE AS SCORE,
    COUNT(*) AS CUSTOMER_COUNT,
    ROUND(
        COUNT(*) * 100.0 / SUM(COUNT(*)) OVER (),
        2
    ) AS CUSTOMER_PERCENTAGE
FROM CUSTOMER_ANALYTICS.ANALYTICS.VW_RFM_SCORES
GROUP BY R_SCORE

UNION ALL

SELECT
    'FREQUENCY' AS METRIC,
    F_SCORE AS SCORE,
    COUNT(*) AS CUSTOMER_COUNT,
    ROUND(
        COUNT(*) * 100.0 / SUM(COUNT(*)) OVER (),
        2
    ) AS CUSTOMER_PERCENTAGE
FROM CUSTOMER_ANALYTICS.ANALYTICS.VW_RFM_SCORES
GROUP BY F_SCORE

UNION ALL

SELECT
    'MONETARY' AS METRIC,
    M_SCORE AS SCORE,
    COUNT(*) AS CUSTOMER_COUNT,
    ROUND(
        COUNT(*) * 100.0 / SUM(COUNT(*)) OVER (),
        2
    ) AS CUSTOMER_PERCENTAGE
FROM CUSTOMER_ANALYTICS.ANALYTICS.VW_RFM_SCORES
GROUP BY M_SCORE

ORDER BY METRIC, SCORE;

-- Create RFM profiles

SELECT
    R_SCORE,
    F_SCORE,
    M_SCORE,
    COUNT(*) AS CUSTOMER_COUNT,
    ROUND(
        COUNT(*) * 100.0 / SUM(COUNT(*)) OVER (),
        2
    ) AS CUSTOMER_PERCENTAGE
FROM CUSTOMER_ANALYTICS.ANALYTICS.VW_RFM_SCORES
GROUP BY
    R_SCORE,
    F_SCORE,
    M_SCORE
ORDER BY
    R_SCORE DESC,
    F_SCORE DESC,
    M_SCORE DESC;

-- Create the customer segmentation view


-- First business-level analysis: Segment performance

SELECT
    CUSTOMER_SEGMENT,

    COUNT(*) AS CUSTOMER_COUNT,

    ROUND(
        COUNT(*) * 100.0 / SUM(COUNT(*)) OVER (),
        2
    ) AS CUSTOMER_PERCENTAGE,

    ROUND(AVG(RECENCY), 2) AS AVG_RECENCY,

    ROUND(AVG(FREQUENCY), 2) AS AVG_FREQUENCY,

    ROUND(AVG(MONETARY), 2) AS AVG_MONETARY,

    ROUND(SUM(MONETARY), 2) AS TOTAL_NET_REVENUE

FROM CUSTOMER_ANALYTICS.ANALYTICS.VW_CUSTOMER_SEGMENTS

GROUP BY CUSTOMER_SEGMENT

ORDER BY TOTAL_NET_REVENUE DESC;

-- validate the segmentation

SELECT
    COUNT(*) AS TOTAL_CUSTOMERS,
    COUNT(DISTINCT CUSTOMER_ID) AS UNIQUE_CUSTOMERS,

    SUM(CASE
        WHEN CUSTOMER_SEGMENT = 'High-Value Active' THEN 1
        ELSE 0
    END) AS HIGH_VALUE_ACTIVE,

    SUM(CASE
        WHEN CUSTOMER_SEGMENT = 'Loyal Customers' THEN 1
        ELSE 0
    END) AS LOYAL_CUSTOMERS,

    SUM(CASE
        WHEN CUSTOMER_SEGMENT = 'High-Potential' THEN 1
        ELSE 0
    END) AS HIGH_POTENTIAL,

    SUM(CASE
        WHEN CUSTOMER_SEGMENT = 'Recent Customers' THEN 1
        ELSE 0
    END) AS RECENT_CUSTOMERS,

    SUM(CASE
        WHEN CUSTOMER_SEGMENT = 'At-Risk Customers' THEN 1
        ELSE 0
    END) AS AT_RISK_CUSTOMERS,

    SUM(CASE
        WHEN CUSTOMER_SEGMENT = 'Dormant Customers' THEN 1
        ELSE 0
    END) AS DORMANT_CUSTOMERS,

    SUM(CASE
        WHEN CUSTOMER_SEGMENT = 'Other Customers' THEN 1
        ELSE 0
    END) AS OTHER_CUSTOMERS

FROM CUSTOMER_ANALYTICS.ANALYTICS.VW_CUSTOMER_SEGMENTS;


-- Validate the cohort activity view

SELECT
    COUNT(*) AS TOTAL_RECORDS,
    COUNT(DISTINCT CUSTOMER_ID) AS UNIQUE_CUSTOMERS,
    COUNT_IF(COHORT_AGE < 0) AS INVALID_COHORT_AGE,
    MIN(COHORT_AGE) AS MIN_COHORT_AGE,
    MAX(COHORT_AGE) AS MAX_COHORT_AGE,
    COUNT_IF(COHORT_MONTH > ACTIVITY_MONTH) AS INVALID_DATE_SEQUENCE
FROM CUSTOMER_ANALYTICS.ANALYTICS.VW_COHORT_ACTIVITY;


-- Validate the retention view

SELECT
    COUNT(*) AS TOTAL_RECORDS,

    COUNT_IF(RETENTION_RATE < 0) AS NEGATIVE_RETENTION,

    COUNT_IF(RETENTION_RATE > 100) AS RETENTION_ABOVE_100,

    COUNT_IF(COHORT_AGE = 0 AND RETENTION_RATE <> 100)
        AS INVALID_INITIAL_RETENTION,

    MIN(RETENTION_RATE) AS MIN_RETENTION,
    MAX(RETENTION_RATE) AS MAX_RETENTION

FROM CUSTOMER_ANALYTICS.ANALYTICS.VW_COHORT_RETENTION;


-- Cohort retention matrix

SELECT
    COHORT_MONTH,

    MAX(IFF(COHORT_AGE = 0, RETENTION_RATE, NULL)) AS MONTH_0,
    MAX(IFF(COHORT_AGE = 1, RETENTION_RATE, NULL)) AS MONTH_1,
    MAX(IFF(COHORT_AGE = 2, RETENTION_RATE, NULL)) AS MONTH_2,
    MAX(IFF(COHORT_AGE = 3, RETENTION_RATE, NULL)) AS MONTH_3,
    MAX(IFF(COHORT_AGE = 4, RETENTION_RATE, NULL)) AS MONTH_4,
    MAX(IFF(COHORT_AGE = 5, RETENTION_RATE, NULL)) AS MONTH_5,
    MAX(IFF(COHORT_AGE = 6, RETENTION_RATE, NULL)) AS MONTH_6,
    MAX(IFF(COHORT_AGE = 7, RETENTION_RATE, NULL)) AS MONTH_7,
    MAX(IFF(COHORT_AGE = 8, RETENTION_RATE, NULL)) AS MONTH_8,
    MAX(IFF(COHORT_AGE = 9, RETENTION_RATE, NULL)) AS MONTH_9,
    MAX(IFF(COHORT_AGE = 10, RETENTION_RATE, NULL)) AS MONTH_10,
    MAX(IFF(COHORT_AGE = 11, RETENTION_RATE, NULL)) AS MONTH_11,
    MAX(IFF(COHORT_AGE = 12, RETENTION_RATE, NULL)) AS MONTH_12

FROM CUSTOMER_ANALYTICS.ANALYTICS.VW_COHORT_RETENTION

GROUP BY COHORT_MONTH
ORDER BY COHORT_MONTH;


SELECT
    COHORT_AGE,

    COUNT(*) AS COHORTS_INCLUDED,

    SUM(COHORT_SIZE) AS ORIGINAL_CUSTOMERS,

    SUM(RETAINED_CUSTOMERS) AS RETAINED_CUSTOMERS,

    ROUND(
        SUM(RETAINED_CUSTOMERS) * 100.0
        / SUM(COHORT_SIZE),
        2
    ) AS WEIGHTED_RETENTION_RATE

FROM CUSTOMER_ANALYTICS.ANALYTICS.VW_COHORT_RETENTION

GROUP BY COHORT_AGE

ORDER BY COHORT_AGE;


-- Recalculate weighted retention

SELECT
    COHORT_AGE,
    COUNT(*) AS COHORTS_INCLUDED,
    SUM(COHORT_SIZE) AS ORIGINAL_CUSTOMERS,
    SUM(RETAINED_CUSTOMERS) AS RETAINED_CUSTOMERS,

    ROUND(
        SUM(RETAINED_CUSTOMERS) * 100.0
        / SUM(COHORT_SIZE),
        2
    ) AS WEIGHTED_RETENTION_RATE

FROM CUSTOMER_ANALYTICS.ANALYTICS.VW_COHORT_RETENTION

GROUP BY COHORT_AGE
ORDER BY COHORT_AGE;

-- Next analysis: Retention by acquisition channel
-- Channel-level cohort retention

WITH CHANNEL_COHORTS AS (
    SELECT
        C.ACQUISITION_CHANNEL,
        A.COHORT_MONTH,
        A.COHORT_AGE,
        A.CUSTOMER_ID
    FROM CUSTOMER_ANALYTICS.ANALYTICS.VW_COHORT_ACTIVITY A

    INNER JOIN CUSTOMER_ANALYTICS.STAGING.STG_CUSTOMERS C
        ON A.CUSTOMER_ID = C.CUSTOMER_ID
),

CHANNEL_COHORT_SIZES AS (
    SELECT
        ACQUISITION_CHANNEL,
        COHORT_MONTH,
        COUNT(DISTINCT CUSTOMER_ID) AS COHORT_SIZE
    FROM CHANNEL_COHORTS
    WHERE COHORT_AGE = 0
    GROUP BY
        ACQUISITION_CHANNEL,
        COHORT_MONTH
),

CHANNEL_ACTIVITY AS (
    SELECT
        ACQUISITION_CHANNEL,
        COHORT_MONTH,
        COHORT_AGE,
        COUNT(DISTINCT CUSTOMER_ID) AS RETAINED_CUSTOMERS
    FROM CHANNEL_COHORTS
    GROUP BY
        ACQUISITION_CHANNEL,
        COHORT_MONTH,
        COHORT_AGE
)

SELECT
    A.ACQUISITION_CHANNEL,
    A.COHORT_AGE,

    SUM(S.COHORT_SIZE) AS ORIGINAL_CUSTOMERS,

    SUM(A.RETAINED_CUSTOMERS) AS RETAINED_CUSTOMERS,

    ROUND(
        SUM(A.RETAINED_CUSTOMERS) * 100.0
        / SUM(S.COHORT_SIZE),
        2
    ) AS RETENTION_RATE

FROM CHANNEL_ACTIVITY A

INNER JOIN CHANNEL_COHORT_SIZES S
    ON A.ACQUISITION_CHANNEL = S.ACQUISITION_CHANNEL
    AND A.COHORT_MONTH = S.COHORT_MONTH

WHERE A.COHORT_AGE IN (1, 3, 6, 12)

GROUP BY
    A.ACQUISITION_CHANNEL,
    A.COHORT_AGE

ORDER BY
    A.ACQUISITION_CHANNEL,
    A.COHORT_AGE;


-- Let's quantify the retention gap

SELECT
    ACQUISITION_CHANNEL,

    MAX(IFF(COHORT_AGE = 1, RETENTION_RATE, NULL))
        AS MONTH_1_RETENTION,

    MAX(IFF(COHORT_AGE = 3, RETENTION_RATE, NULL))
        AS MONTH_3_RETENTION,

    MAX(IFF(COHORT_AGE = 6, RETENTION_RATE, NULL))
        AS MONTH_6_RETENTION,

    MAX(IFF(COHORT_AGE = 12, RETENTION_RATE, NULL))
        AS MONTH_12_RETENTION,

    ROUND(
        MAX(IFF(COHORT_AGE = 1, RETENTION_RATE, NULL))
        -
        MAX(IFF(COHORT_AGE = 12, RETENTION_RATE, NULL)),
        2
    ) AS RETENTION_GAP_PP

FROM (
    SELECT
        ACQUISITION_CHANNEL,
        COHORT_AGE,
        SUM(RETAINED_CUSTOMERS) * 100.0
            / SUM(COHORT_SIZE) AS RETENTION_RATE

    FROM (
        SELECT
            C.ACQUISITION_CHANNEL,
            R.COHORT_MONTH,
            R.COHORT_AGE,
            R.COHORT_SIZE,
            R.RETAINED_CUSTOMERS

        FROM CUSTOMER_ANALYTICS.ANALYTICS.VW_COHORT_RETENTION R

        INNER JOIN (
            SELECT DISTINCT
                CUSTOMER_ID,
                ACQUISITION_CHANNEL
            FROM CUSTOMER_ANALYTICS.STAGING.STG_CUSTOMERS
        ) C
            ON R.COHORT_MONTH IS NOT NULL
            AND R.COHORT_MONTH = (
                SELECT MIN(A.COHORT_MONTH)
                FROM CUSTOMER_ANALYTICS.ANALYTICS.VW_COHORT_ACTIVITY A
                WHERE A.CUSTOMER_ID = C.CUSTOMER_ID
            )
    )
    WHERE COHORT_AGE IN (1, 3, 6, 12)

    GROUP BY ACQUISITION_CHANNEL, COHORT_AGE
)

GROUP BY ACQUISITION_CHANNEL
ORDER BY MONTH_12_RETENTION DESC;

-- Retention by region


WITH CUSTOMER_COHORTS AS (
    SELECT DISTINCT
        A.CUSTOMER_ID,
        A.COHORT_MONTH,
        C.REGION
    FROM CUSTOMER_ANALYTICS.ANALYTICS.VW_COHORT_ACTIVITY A
    INNER JOIN CUSTOMER_ANALYTICS.STAGING.STG_CUSTOMERS C
        ON A.CUSTOMER_ID = C.CUSTOMER_ID
    WHERE A.COHORT_AGE = 0
),

COHORT_SIZES AS (
    SELECT
        REGION,
        COHORT_MONTH,
        COUNT(DISTINCT CUSTOMER_ID) AS COHORT_SIZE
    FROM CUSTOMER_COHORTS
    GROUP BY REGION, COHORT_MONTH
),

AGE_MILESTONES AS (
    SELECT 1 AS COHORT_AGE
    UNION ALL SELECT 3
    UNION ALL SELECT 6
    UNION ALL SELECT 12
),

COHORT_GRID AS (
    SELECT
        C.REGION,
        C.COHORT_MONTH,
        C.COHORT_SIZE,
        M.COHORT_AGE
    FROM COHORT_SIZES C
    CROSS JOIN AGE_MILESTONES M
    WHERE DATEADD(MONTH, M.COHORT_AGE, C.COHORT_MONTH)
          <= DATE '2024-12-01'
),

MONTHLY_ACTIVITY AS (
    SELECT
        C.REGION,
        A.COHORT_MONTH,
        A.COHORT_AGE,
        COUNT(DISTINCT A.CUSTOMER_ID) AS RETAINED_CUSTOMERS
    FROM CUSTOMER_ANALYTICS.ANALYTICS.VW_COHORT_ACTIVITY A
    INNER JOIN CUSTOMER_COHORTS C
        ON A.CUSTOMER_ID = C.CUSTOMER_ID
       AND A.COHORT_MONTH = C.COHORT_MONTH
    WHERE A.COHORT_AGE IN (1, 3, 6, 12)
    GROUP BY
        C.REGION,
        A.COHORT_MONTH,
        A.COHORT_AGE
)

SELECT
    G.REGION,
    G.COHORT_AGE,
    COUNT(*) AS COHORTS_INCLUDED,
    SUM(G.COHORT_SIZE) AS ORIGINAL_CUSTOMERS,
    SUM(COALESCE(A.RETAINED_CUSTOMERS, 0)) AS RETAINED_CUSTOMERS,
    ROUND(
        SUM(COALESCE(A.RETAINED_CUSTOMERS, 0)) * 100.0
        / SUM(G.COHORT_SIZE),
        2
    ) AS WEIGHTED_RETENTION_RATE
FROM COHORT_GRID G
LEFT JOIN MONTHLY_ACTIVITY A
    ON G.REGION = A.REGION
   AND G.COHORT_MONTH = A.COHORT_MONTH
   AND G.COHORT_AGE = A.COHORT_AGE
GROUP BY
    G.REGION,
    G.COHORT_AGE
ORDER BY
    G.REGION,
    G.COHORT_AGE;
