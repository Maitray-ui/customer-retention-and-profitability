-- 1. RFM BASE
-- One row per customer with completed-order recency, frequency,
-- and monetary value. Recency is measured against 2024-12-31.
CREATE OR REPLACE VIEW CUSTOMER_ANALYTICS.ANALYTICS.VW_RFM_BASE AS

WITH CUSTOMER_PURCHASES AS (
    SELECT
        CUSTOMER_ID,
        COUNT(DISTINCT ORDER_ID) AS FREQUENCY,
        MAX(ORDER_DATE) AS LAST_PURCHASE_DATE,
        SUM(NET_REVENUE) AS MONETARY
    FROM CUSTOMER_ANALYTICS.STAGING.STG_ORDERS
    WHERE IS_COMPLETED_ORDER = TRUE
    GROUP BY CUSTOMER_ID
)

SELECT
    C.CUSTOMER_ID,
    C.ACQUISITION_CHANNEL,
    C.REGION,
    C.SIGNUP_DATE,

    P.LAST_PURCHASE_DATE,

    DATEDIFF(
        'DAY',
        P.LAST_PURCHASE_DATE,
        DATE '2024-12-31'
    ) AS RECENCY,

    P.FREQUENCY,
    P.MONETARY

FROM CUSTOMER_PURCHASES P
INNER JOIN CUSTOMER_ANALYTICS.STAGING.STG_CUSTOMERS C
    ON P.CUSTOMER_ID = C.CUSTOMER_ID;


-- 2. RFM SCORES
-- Assigns each customer a 1-5 score for recency, frequency,
-- and monetary value. Higher scores represent stronger RFM performance.
CREATE OR REPLACE VIEW CUSTOMER_ANALYTICS.ANALYTICS.VW_RFM_SCORES AS

SELECT
    CUSTOMER_ID,
    ACQUISITION_CHANNEL,
    REGION,
    LAST_PURCHASE_DATE,
    RECENCY,
    FREQUENCY,
    MONETARY,

    6 - NTILE(5) OVER (
        ORDER BY RECENCY ASC, CUSTOMER_ID
    ) AS R_SCORE,

    6 - NTILE(5) OVER (
        ORDER BY FREQUENCY DESC, CUSTOMER_ID
    ) AS F_SCORE,

    6 - NTILE(5) OVER (
        ORDER BY MONETARY DESC, CUSTOMER_ID
    ) AS M_SCORE

FROM CUSTOMER_ANALYTICS.ANALYTICS.VW_RFM_BASE;


-- 3. CUSTOMER SEGMENTS
-- Converts RFM scores into business-facing customer groups,
-- such as High-Value Active, Loyal, At-Risk, and Dormant.
CREATE OR REPLACE VIEW CUSTOMER_ANALYTICS.ANALYTICS.VW_CUSTOMER_SEGMENTS AS

SELECT
    CUSTOMER_ID,
    ACQUISITION_CHANNEL,
    REGION,
    LAST_PURCHASE_DATE,
    RECENCY,
    FREQUENCY,
    MONETARY,

    R_SCORE,
    F_SCORE,
    M_SCORE,

    CONCAT(R_SCORE, F_SCORE, M_SCORE) AS RFM_SCORE,

    CASE
        WHEN R_SCORE >= 4
         AND F_SCORE >= 4
         AND M_SCORE >= 4
            THEN 'High-Value Active'

        WHEN R_SCORE >= 3
         AND F_SCORE >= 4
            THEN 'Loyal Customers'

        WHEN R_SCORE >= 4
         AND F_SCORE BETWEEN 2 AND 3
         AND M_SCORE >= 3
            THEN 'High-Potential'

        WHEN R_SCORE = 5
         AND F_SCORE = 1
            THEN 'Recent Customers'

        WHEN R_SCORE <= 2
         AND (F_SCORE >= 4 OR M_SCORE >= 4)
            THEN 'At-Risk Customers'

        WHEN R_SCORE <= 2
         AND F_SCORE <= 2
         AND M_SCORE <= 2
            THEN 'Dormant Customers'

        ELSE 'Other Customers'

    END AS CUSTOMER_SEGMENT

FROM CUSTOMER_ANALYTICS.ANALYTICS.VW_RFM_SCORES;


-- 4. COHORT ACTIVITY
-- Identifies each customer's first-purchase month and every
-- subsequent month in which they placed a completed order.
CREATE OR REPLACE VIEW CUSTOMER_ANALYTICS.ANALYTICS.VW_COHORT_ACTIVITY AS

WITH FIRST_PURCHASE AS (
    SELECT
        CUSTOMER_ID,
        DATE_TRUNC('MONTH', MIN(ORDER_DATE)) AS COHORT_MONTH
    FROM CUSTOMER_ANALYTICS.STAGING.STG_ORDERS
    WHERE IS_COMPLETED_ORDER = TRUE
    GROUP BY CUSTOMER_ID
),

MONTHLY_ACTIVITY AS (
    SELECT DISTINCT
        CUSTOMER_ID,
        DATE_TRUNC('MONTH', ORDER_DATE) AS ACTIVITY_MONTH
    FROM CUSTOMER_ANALYTICS.STAGING.STG_ORDERS
    WHERE IS_COMPLETED_ORDER = TRUE
)

SELECT
    F.CUSTOMER_ID,
    F.COHORT_MONTH,
    A.ACTIVITY_MONTH,

    DATEDIFF(
        'MONTH',
        F.COHORT_MONTH,
        A.ACTIVITY_MONTH
    ) AS COHORT_AGE

FROM FIRST_PURCHASE F

INNER JOIN MONTHLY_ACTIVITY A
    ON F.CUSTOMER_ID = A.CUSTOMER_ID;


-- 5. COHORT RETENTION
-- Builds a cohort-month and cohort-age grid, including months
-- with zero repeat activity, then calculates retention rates.
CREATE OR REPLACE VIEW CUSTOMER_ANALYTICS.ANALYTICS.VW_COHORT_RETENTION AS

WITH COHORT_SIZES AS (
    SELECT
        COHORT_MONTH,
        COUNT(DISTINCT CUSTOMER_ID) AS COHORT_SIZE
    FROM CUSTOMER_ANALYTICS.ANALYTICS.VW_COHORT_ACTIVITY
    WHERE COHORT_AGE = 0
    GROUP BY COHORT_MONTH
),

COHORT_MONTH_GRID AS (
    SELECT
        C.COHORT_MONTH,
        D.ACTIVITY_MONTH,
        C.COHORT_SIZE,

        DATEDIFF(
            'MONTH',
            C.COHORT_MONTH,
            D.ACTIVITY_MONTH
        ) AS COHORT_AGE

    FROM COHORT_SIZES C

    INNER JOIN (
        SELECT DISTINCT
            DATE_TRUNC('MONTH', DATE) AS ACTIVITY_MONTH
        FROM CUSTOMER_ANALYTICS.STAGING.STG_DATE_DIM
    ) D
        ON D.ACTIVITY_MONTH >= C.COHORT_MONTH
),

MONTHLY_ACTIVITY AS (
    SELECT
        COHORT_MONTH,
        COHORT_AGE,
        COUNT(DISTINCT CUSTOMER_ID) AS RETAINED_CUSTOMERS
    FROM CUSTOMER_ANALYTICS.ANALYTICS.VW_COHORT_ACTIVITY
    GROUP BY
        COHORT_MONTH,
        COHORT_AGE
)

SELECT
    G.COHORT_MONTH,
    G.COHORT_AGE,
    G.COHORT_SIZE,

    COALESCE(
        M.RETAINED_CUSTOMERS,
        0
    ) AS RETAINED_CUSTOMERS,

    ROUND(
        COALESCE(M.RETAINED_CUSTOMERS, 0) * 100.0
        / G.COHORT_SIZE,
        2
    ) AS RETENTION_RATE

FROM COHORT_MONTH_GRID G

LEFT JOIN MONTHLY_ACTIVITY M
    ON G.COHORT_MONTH = M.COHORT_MONTH
    AND G.COHORT_AGE = M.COHORT_AGE;


-- 6. MARKETING PERFORMANCE BY CHANNEL
-- Aggregates spend, impressions, clicks, conversions, and new
-- customers by channel; calculates CTR, conversion rate, and
-- cost per new customer.
CREATE OR REPLACE VIEW
CUSTOMER_ANALYTICS.ANALYTICS.VW_MARKETING_CHANNEL_PERFORMANCE AS

SELECT
    CHANNEL,
    COUNT(*) AS MONTHLY_RECORDS,
    ROUND(SUM(SPEND_AMOUNT), 2) AS TOTAL_SPEND,
    SUM(IMPRESSIONS) AS TOTAL_IMPRESSIONS,
    SUM(CLICKS) AS TOTAL_CLICKS,
    SUM(CONVERSIONS) AS TOTAL_CONVERSIONS,
    SUM(NEW_CUSTOMERS) AS TOTAL_NEW_CUSTOMERS,

    ROUND(
        SUM(CLICKS) * 100.0 /
        NULLIF(SUM(IMPRESSIONS), 0), 2
    ) AS OVERALL_CTR,

    ROUND(
        SUM(CONVERSIONS) * 100.0 /
        NULLIF(SUM(CLICKS), 0), 2
    ) AS OVERALL_CONVERSION_RATE,

    ROUND(
        SUM(SPEND_AMOUNT) /
        NULLIF(SUM(NEW_CUSTOMERS), 0), 2
    ) AS COST_PER_NEW_CUSTOMER

FROM CUSTOMER_ANALYTICS.STAGING.STG_MARKETING_SPEND
GROUP BY CHANNEL;


