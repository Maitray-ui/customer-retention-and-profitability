-- 8. MONTHLY MARKETING PERFORMANCE
-- Tracks marketing spend and funnel efficiency by month and channel.
CREATE OR REPLACE VIEW
CUSTOMER_ANALYTICS.ANALYTICS.VW_MARKETING_MONTHLY_PERFORMANCE AS

SELECT
    MONTH,
    CHANNEL,

    ROUND(SUM(SPEND_AMOUNT), 2) AS TOTAL_SPEND,
    SUM(IMPRESSIONS) AS TOTAL_IMPRESSIONS,
    SUM(CLICKS) AS TOTAL_CLICKS,
    SUM(CONVERSIONS) AS TOTAL_CONVERSIONS,
    SUM(NEW_CUSTOMERS) AS TOTAL_NEW_CUSTOMERS,

    ROUND(
        SUM(CLICKS) * 100.0 /
        NULLIF(SUM(IMPRESSIONS), 0), 2
    ) AS CTR,

    ROUND(
        SUM(CONVERSIONS) * 100.0 /
        NULLIF(SUM(CLICKS), 0), 2
    ) AS CONVERSION_RATE,

    ROUND(
        SUM(SPEND_AMOUNT) /
        NULLIF(SUM(NEW_CUSTOMERS), 0), 2
    ) AS COST_PER_NEW_CUSTOMER

FROM CUSTOMER_ANALYTICS.STAGING.STG_MARKETING_SPEND
GROUP BY
    MONTH,
    CHANNEL;


