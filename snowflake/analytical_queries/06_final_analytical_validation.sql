-- Final analytical view, integrity, retention, and marketing validation
-- Source: 03_analytical_views.sql
-- Organized for the Customer Retention & Profitability project.

-- =====================================================
-- FINAL SECTION: ANALYTICAL VIEW VALIDATION
-- =====================================================

SELECT
    TABLE_NAME AS VIEW_NAME,
    CREATED,
    LAST_ALTERED
FROM CUSTOMER_ANALYTICS.INFORMATION_SCHEMA.VIEWS
WHERE TABLE_SCHEMA = 'ANALYTICS'
ORDER BY TABLE_NAME;

-- Step 2: Validate analytical view row counts

SELECT 'VW_RFM_BASE' AS VIEW_NAME,
       COUNT(*) AS TOTAL_ROWS
FROM CUSTOMER_ANALYTICS.ANALYTICS.VW_RFM_BASE

UNION ALL

SELECT 'VW_RFM_SCORES', COUNT(*)
FROM CUSTOMER_ANALYTICS.ANALYTICS.VW_RFM_SCORES

UNION ALL

SELECT 'VW_CUSTOMER_SEGMENTS', COUNT(*)
FROM CUSTOMER_ANALYTICS.ANALYTICS.VW_CUSTOMER_SEGMENTS

UNION ALL

SELECT 'VW_COHORT_ACTIVITY', COUNT(*)
FROM CUSTOMER_ANALYTICS.ANALYTICS.VW_COHORT_ACTIVITY

UNION ALL

SELECT 'VW_COHORT_RETENTION', COUNT(*)
FROM CUSTOMER_ANALYTICS.ANALYTICS.VW_COHORT_RETENTION

UNION ALL

SELECT 'VW_MARKETING_CHANNEL_PERFORMANCE', COUNT(*)
FROM CUSTOMER_ANALYTICS.ANALYTICS.VW_MARKETING_CHANNEL_PERFORMANCE

UNION ALL

SELECT 'VW_MARKETING_REGION_PERFORMANCE', COUNT(*)
FROM CUSTOMER_ANALYTICS.ANALYTICS.VW_MARKETING_REGION_PERFORMANCE

UNION ALL

SELECT 'VW_MARKETING_MONTHLY_PERFORMANCE', COUNT(*)
FROM CUSTOMER_ANALYTICS.ANALYTICS.VW_MARKETING_MONTHLY_PERFORMANCE

UNION ALL

SELECT 'VW_MARKETING_CHANNEL_REGION_PERFORMANCE', COUNT(*)
FROM CUSTOMER_ANALYTICS.ANALYTICS.VW_MARKETING_CHANNEL_REGION_PERFORMANCE

UNION ALL

SELECT 'VW_MARKETING_YEARLY_PERFORMANCE', COUNT(*)
FROM CUSTOMER_ANALYTICS.ANALYTICS.VW_MARKETING_YEARLY_PERFORMANCE;


-- Step 3: Final integrity check
SELECT
    COUNT(*) AS TOTAL_ROWS,
    COUNT(DISTINCT CUSTOMER_ID) AS UNIQUE_CUSTOMERS,
    COUNT_IF(CUSTOMER_SEGMENT IS NULL) AS NULL_SEGMENTS
FROM CUSTOMER_ANALYTICS.ANALYTICS.VW_CUSTOMER_SEGMENTS;

DESC VIEW CUSTOMER_ANALYTICS.ANALYTICS.VW_CUSTOMER_SEGMENTS;

-- Step 4: Cohort retention integrity

SELECT
    COUNT(*) AS TOTAL_RECORDS,

    COUNT_IF(
        RETENTION_RATE < 0 OR RETENTION_RATE > 100
    ) AS INVALID_RETENTION_RATES,

    COUNT_IF(
        COHORT_AGE = 0 AND RETENTION_RATE <> 100
    ) AS INVALID_MONTH_ZERO,

    COUNT_IF(
        RETENTION_RATE IS NULL
    ) AS NULL_RETENTION_RATES

FROM CUSTOMER_ANALYTICS.ANALYTICS.VW_COHORT_RETENTION;


-- Step 5: Final marketing reconciliation

SELECT
    ROUND(SUM(SPEND_AMOUNT), 2) AS SOURCE_TOTAL_SPEND,
    (
        SELECT ROUND(SUM(TOTAL_SPEND), 2)
        FROM CUSTOMER_ANALYTICS.ANALYTICS.VW_MARKETING_YEARLY_PERFORMANCE
    ) AS YEARLY_VIEW_TOTAL_SPEND,

    SUM(NEW_CUSTOMERS) AS SOURCE_NEW_CUSTOMERS,
    (
        SELECT SUM(TOTAL_NEW_CUSTOMERS)
        FROM CUSTOMER_ANALYTICS.ANALYTICS.VW_MARKETING_YEARLY_PERFORMANCE
    ) AS YEARLY_VIEW_NEW_CUSTOMERS

FROM CUSTOMER_ANALYTICS.STAGING.STG_MARKETING_SPEND;
