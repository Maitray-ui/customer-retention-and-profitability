WITH COMPLETED_ORDER_METRICS AS (
    SELECT
        CUSTOMER_ID,
        COUNT(DISTINCT ORDER_ID) AS CALCULATED_FREQUENCY,
        MAX(ORDER_DATE) AS LAST_ORDER_DATE,
        DATEDIFF(
            DAY,
            MAX(ORDER_DATE),
            '2024-12-31'::DATE
        ) AS CALCULATED_RECENCY
    FROM CUSTOMER_ANALYTICS.STAGING.STG_ORDERS
    WHERE IS_COMPLETED_ORDER = TRUE
      AND ORDER_DATE <= '2024-12-31'
    GROUP BY CUSTOMER_ID
),

FEATURE_COMPARISON AS (
    SELECT
        F.CUSTOMER_ID,
        F.ORDER_FREQUENCY,
        O.CALCULATED_FREQUENCY,
        F.DAYS_SINCE_LAST_ORDER,
        O.CALCULATED_RECENCY,

        CASE
            WHEN F.ORDER_FREQUENCY = O.CALCULATED_FREQUENCY
                THEN 'MATCH'
            ELSE 'MISMATCH'
        END AS FREQUENCY_CHECK,

        CASE
            WHEN F.DAYS_SINCE_LAST_ORDER = O.CALCULATED_RECENCY
                THEN 'MATCH'
            ELSE 'MISMATCH'
        END AS RECENCY_CHECK

    FROM CUSTOMER_ANALYTICS.STAGING.STG_CUSTOMER_FEATURES F
    LEFT JOIN COMPLETED_ORDER_METRICS O
        ON F.CUSTOMER_ID = O.CUSTOMER_ID
)

SELECT
    FREQUENCY_CHECK,
    RECENCY_CHECK,
    COUNT(*) AS CUSTOMER_COUNT
FROM FEATURE_COMPARISON
GROUP BY
    FREQUENCY_CHECK,
    RECENCY_CHECK
ORDER BY
    FREQUENCY_CHECK,
    RECENCY_CHECK;


SELECT
    CUSTOMER_SEGMENT,
    SUM(CUSTOMER_COUNT) AS CUSTOMERS,
    SUM(TOTAL_ORDERS) AS ORDERS,
    ROUND(SUM(TOTAL_REVENUE), 2) AS REVENUE,
    ROUND(SUM(TOTAL_CONTRIBUTION), 2) AS CONTRIBUTION
FROM CUSTOMER_ANALYTICS.ANALYTICS.CUSTOMER_SEGMENTS
GROUP BY CUSTOMER_SEGMENT
ORDER BY CUSTOMERS DESC;


SELECT *
