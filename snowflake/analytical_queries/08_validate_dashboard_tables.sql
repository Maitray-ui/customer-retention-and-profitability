SELECT *
FROM CUSTOMER_ANALYTICS.STAGING.STG_SUBSCRIPTION_HISTORY
LIMIT 10;


SELECT
    SUBSCRIPTION_TIER,
    SUM(TOTAL_SUBSCRIPTIONS_ENDED) AS TOTAL_SUBSCRIPTIONS,
    SUM(CHURNED_SUBSCRIPTIONS) AS CHURNED,
    SUM(REACTIVATED_SUBSCRIPTIONS) AS REACTIVATED,

    ROUND(
        SUM(CHURNED_SUBSCRIPTIONS)
        / NULLIF(SUM(TOTAL_SUBSCRIPTIONS_ENDED), 0) * 100,
        2
    ) AS CHURN_RATE,

    ROUND(SUM(LOST_MONTHLY_REVENUE), 2)
        AS LOST_MONTHLY_REVENUE

FROM CUSTOMER_ANALYTICS.ANALYTICS.SUBSCRIPTION_CHURN

GROUP BY SUBSCRIPTION_TIER
ORDER BY CHURN_RATE DESC;



