SELECT *
FROM CUSTOMER_ANALYTICS.ANALYTICS.COHORT_RETENTION
ORDER BY COHORT_MONTH, COHORT_AGE, REGION, ACQUISITION_CHANNEL;




SELECT
    COHORT_MONTH,
    COHORT_AGE,
    SUM(COHORT_SIZE) AS COHORT_SIZE,
    SUM(ACTIVE_CUSTOMERS) AS ACTIVE_CUSTOMERS,

    ROUND(
        SUM(ACTIVE_CUSTOMERS)
        / NULLIF(SUM(COHORT_SIZE), 0) * 100,
        2
    ) AS RETENTION_RATE

FROM CUSTOMER_ANALYTICS.ANALYTICS.COHORT_RETENTION

GROUP BY COHORT_MONTH, COHORT_AGE
ORDER BY COHORT_MONTH, COHORT_AGE;


SELECT
    ACQUISITION_CHANNEL,
    SUM(NEW_CUSTOMERS) AS NEW_CUSTOMERS,
    ROUND(SUM(ACQUISITION_SPEND), 2) AS ACQUISITION_SPEND,
    ROUND(SUM(TOTAL_REVENUE), 2) AS REVENUE,
    ROUND(SUM(TOTAL_CONTRIBUTION), 2) AS CONTRIBUTION
FROM CUSTOMER_ANALYTICS.ANALYTICS.ACQUISITION_PERFORMANCE
GROUP BY ACQUISITION_CHANNEL
ORDER BY NEW_CUSTOMERS DESC;


