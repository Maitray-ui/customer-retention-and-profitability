-- Project: Customer Retention & Profitability
-- Source: 01_raw_setup_and_validation.sql
-- Purpose: Validate row counts, key uniqueness, relationships, and source coverage.
-- Run after loading the seven raw tables.

USE DATABASE CUSTOMER_ANALYTICS;
USE SCHEMA RAW;

-- 1. Inspect sample records
SELECT * FROM CUSTOMERS LIMIT 10;
SELECT * FROM ORDERS LIMIT 10;

-- 2. Validate expected row counts across all seven tables
-- Expected counts are retained from the source script.
SELECT 'CUSTOMERS' AS TABLE_NAME, COUNT(*) AS ACTUAL_ROWS, 204227 AS EXPECTED_ROWS
FROM CUSTOMERS
UNION ALL
SELECT 'ORDERS', COUNT(*), 1126821 FROM ORDERS
UNION ALL
SELECT 'CUSTOMER_FEATURES', COUNT(*), 204227 FROM CUSTOMER_FEATURES
UNION ALL
SELECT 'CUSTOMER_UNIT_ECONOMICS', COUNT(*), 204227 FROM CUSTOMER_UNIT_ECONOMICS
UNION ALL
SELECT 'SUBSCRIPTION_HISTORY', COUNT(*), 2201060 FROM SUBSCRIPTION_HISTORY
UNION ALL
SELECT 'MARKETING_SPEND', COUNT(*), 960 FROM MARKETING_SPEND
UNION ALL
SELECT 'DATE_DIM', COUNT(*), 1461 FROM DATE_DIM;

-- 3. Primary-key / uniqueness checks for tables with a single candidate key
-- These queries report the values; they do not enforce constraints.
SELECT
    'CUSTOMERS' AS TABLE_NAME,
    COUNT(*) AS TOTAL_ROWS,
    COUNT(CUSTOMER_ID) AS NON_NULL_KEYS,
    COUNT(DISTINCT CUSTOMER_ID) AS UNIQUE_KEYS
FROM CUSTOMERS
UNION ALL
SELECT 'ORDERS', COUNT(*), COUNT(ORDER_ID), COUNT(DISTINCT ORDER_ID)
FROM ORDERS
UNION ALL
SELECT 'CUSTOMER_FEATURES', COUNT(*), COUNT(CUSTOMER_ID), COUNT(DISTINCT CUSTOMER_ID)
FROM CUSTOMER_FEATURES
UNION ALL
SELECT 'CUSTOMER_UNIT_ECONOMICS', COUNT(*), COUNT(CUSTOMER_ID), COUNT(DISTINCT CUSTOMER_ID)
FROM CUSTOMER_UNIT_ECONOMICS
UNION ALL
SELECT 'SUBSCRIPTION_HISTORY', COUNT(*), COUNT(SUBSCRIPTION_ID), COUNT(DISTINCT SUBSCRIPTION_ID)
FROM SUBSCRIPTION_HISTORY
UNION ALL
SELECT 'DATE_DIM', COUNT(*), COUNT(DATE), COUNT(DISTINCT DATE)
FROM DATE_DIM;

-- MARKETING_SPEND does not have an identified single-column key in the source.
-- Do not treat MONTH alone as its primary key. Investigate the proposed
-- composite combination (MONTH, CHANNEL, REGION, CAMPAIGN_ID) instead.
SELECT
    COUNT(*) AS TOTAL_ROWS,
    COUNT(DISTINCT CONCAT(
        TO_VARCHAR(MONTH), '|',
        CHANNEL, '|',
        REGION, '|',
        CAMPAIGN_ID
    )) AS UNIQUE_COMBINATIONS
FROM MARKETING_SPEND;

-- Check repeated MONTH / CHANNEL / REGION combinations.
-- Multiple campaigns may legitimately create multiple rows for a combination.
SELECT
    MONTH,
    CHANNEL,
    REGION,
    COUNT(*) AS RECORD_COUNT
FROM MARKETING_SPEND
GROUP BY MONTH, CHANNEL, REGION
HAVING COUNT(*) > 1
ORDER BY RECORD_COUNT DESC;

-- 4. Understand marketing-spend dimensions and coverage
SELECT
    COUNT(DISTINCT MONTH) AS DISTINCT_MONTHS,
    COUNT(DISTINCT CHANNEL) AS DISTINCT_CHANNELS,
    COUNT(DISTINCT REGION) AS DISTINCT_REGIONS
FROM MARKETING_SPEND;

SELECT
    CHANNEL,
    REGION,
    COUNT(DISTINCT MONTH) AS MONTHS_PRESENT
FROM MARKETING_SPEND
GROUP BY CHANNEL, REGION
ORDER BY CHANNEL, REGION;

-- 5. Foreign-key / relationship validation
SELECT
    COUNT(*) AS TOTAL_ORDERS,
    COUNT(o.CUSTOMER_ID) AS ORDERS_WITH_CUSTOMER_ID,
    COUNT(c.CUSTOMER_ID) AS MATCHED_CUSTOMERS
FROM ORDERS o
LEFT JOIN CUSTOMERS c
    ON o.CUSTOMER_ID = c.CUSTOMER_ID;

SELECT
    COUNT(*) AS TOTAL_FEATURE_RECORDS,
    COUNT(cf.CUSTOMER_ID) AS NON_NULL_CUSTOMER_IDS,
    COUNT(c.CUSTOMER_ID) AS MATCHED_CUSTOMERS
FROM CUSTOMER_FEATURES cf
LEFT JOIN CUSTOMERS c
    ON cf.CUSTOMER_ID = c.CUSTOMER_ID;

SELECT
    COUNT(*) AS TOTAL_RECORDS,
    COUNT(cu.CUSTOMER_ID) AS NON_NULL_CUSTOMER_IDS,
    COUNT(c.CUSTOMER_ID) AS MATCHED_CUSTOMERS
FROM CUSTOMER_UNIT_ECONOMICS cu
LEFT JOIN CUSTOMERS c
    ON cu.CUSTOMER_ID = c.CUSTOMER_ID;

SELECT
    COUNT(*) AS TOTAL_SUBSCRIPTIONS,
    COUNT(sh.CUSTOMER_ID) AS NON_NULL_CUSTOMER_IDS,
    COUNT(c.CUSTOMER_ID) AS MATCHED_CUSTOMERS
FROM SUBSCRIPTION_HISTORY sh
LEFT JOIN CUSTOMERS c
    ON sh.CUSTOMER_ID = c.CUSTOMER_ID;

-- 6. Date dimension coverage
SELECT
    COUNT(*) AS TOTAL_ORDERS,
    COUNT(d.DATE) AS MATCHED_DATES
FROM ORDERS o
LEFT JOIN DATE_DIM d
    ON o.ORDER_DATE = d.DATE;

-- The source script joined MONTH directly to DATE. This assumes MONTH is
-- stored as a date corresponding to a date present in DATE_DIM. Verify the
-- YYYY-MM loading convention before interpreting this as complete coverage.
SELECT
    COUNT(*) AS TOTAL_MARKETING_RECORDS,
    COUNT(d.DATE) AS MATCHED_DATES
FROM MARKETING_SPEND m
LEFT JOIN DATE_DIM d
    ON m.MONTH = d.DATE;

-- 7. Inspect the loaded MARKETING_SPEND column type
SELECT
    COLUMN_NAME,
    DATA_TYPE
FROM CUSTOMER_ANALYTICS.INFORMATION_SCHEMA.COLUMNS
WHERE TABLE_SCHEMA = 'RAW'
  AND TABLE_NAME = 'MARKETING_SPEND'
ORDER BY ORDINAL_POSITION;

-- 8. Inspect raw staged marketing CSV values
SELECT
    $1 AS MONTH_VALUE,
    $2 AS CHANNEL,
    $3 AS REGION
FROM @CUSTOMER_DATA_STAGE/marketing_spend.csv
(FILE_FORMAT => 'CUSTOMER_CSV_FORMAT')
LIMIT 5;
