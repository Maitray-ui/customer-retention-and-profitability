-- Project: Customer Retention & Profitability
-- Source: 01_raw_setup_and_validation.sql
-- Purpose: Define the CSV file format, create an internal stage, and load raw tables.
-- Run after creating the database, RAW schema, and raw tables.

USE DATABASE CUSTOMER_ANALYTICS;
USE SCHEMA RAW;

-- 1. CSV file format
CREATE OR REPLACE FILE FORMAT CUSTOMER_CSV_FORMAT
    TYPE = CSV
    SKIP_HEADER = 1
    FIELD_OPTIONALLY_ENCLOSED_BY = '"'
    EMPTY_FIELD_AS_NULL = TRUE;

SHOW FILE FORMATS IN SCHEMA CUSTOMER_ANALYTICS.RAW;

-- 2. Internal stage
CREATE STAGE IF NOT EXISTS CUSTOMER_DATA_STAGE
    FILE_FORMAT = CUSTOMER_CSV_FORMAT;

SHOW STAGES IN SCHEMA CUSTOMER_ANALYTICS.RAW;

-- Upload the seven CSV files to this stage before running the COPY commands.
-- Confirm their exact staged paths with:
LIST @CUSTOMER_DATA_STAGE;

-- 3. Load the source files
-- These paths assume each CSV is located at the root of CUSTOMER_DATA_STAGE.
-- If LIST @CUSTOMER_DATA_STAGE shows a different path, update the FROM path.

COPY INTO CUSTOMERS
FROM @CUSTOMER_DATA_STAGE/customers.csv
FILE_FORMAT = (FORMAT_NAME = 'CUSTOMER_CSV_FORMAT')
ON_ERROR = 'ABORT_STATEMENT';

COPY INTO ORDERS
FROM @CUSTOMER_DATA_STAGE/orders.csv
FILE_FORMAT = (FORMAT_NAME = 'CUSTOMER_CSV_FORMAT')
ON_ERROR = 'ABORT_STATEMENT';

COPY INTO CUSTOMER_FEATURES
FROM @CUSTOMER_DATA_STAGE/customer_features.csv
FILE_FORMAT = (FORMAT_NAME = 'CUSTOMER_CSV_FORMAT')
ON_ERROR = 'ABORT_STATEMENT';

COPY INTO CUSTOMER_UNIT_ECONOMICS
FROM @CUSTOMER_DATA_STAGE/customer_unit_economics.csv
FILE_FORMAT = (FORMAT_NAME = 'CUSTOMER_CSV_FORMAT')
ON_ERROR = 'ABORT_STATEMENT';

COPY INTO SUBSCRIPTION_HISTORY
FROM @CUSTOMER_DATA_STAGE/subscription_history.csv
FILE_FORMAT = (FORMAT_NAME = 'CUSTOMER_CSV_FORMAT')
ON_ERROR = 'ABORT_STATEMENT';

COPY INTO MARKETING_SPEND
FROM @CUSTOMER_DATA_STAGE/marketing_spend.csv
FILE_FORMAT = (
    FORMAT_NAME = 'CUSTOMER_CSV_FORMAT'
    DATE_FORMAT = 'YYYY-MM'
)
ON_ERROR = 'ABORT_STATEMENT';

COPY INTO DATE_DIM
FROM @CUSTOMER_DATA_STAGE/date_dim.csv
FILE_FORMAT = (FORMAT_NAME = 'CUSTOMER_CSV_FORMAT')
ON_ERROR = 'ABORT_STATEMENT';

-- 4. Optional post-load row-count spot checks
SELECT COUNT(*) AS CUSTOMER_ROWS FROM CUSTOMERS;
SELECT COUNT(*) AS ORDER_ROWS FROM ORDERS;
SELECT COUNT(*) AS CUSTOMER_FEATURE_ROWS FROM CUSTOMER_FEATURES;
SELECT COUNT(*) AS CUSTOMER_UNIT_ECONOMICS_ROWS FROM CUSTOMER_UNIT_ECONOMICS;
SELECT COUNT(*) AS SUBSCRIPTION_HISTORY_ROWS FROM SUBSCRIPTION_HISTORY;
SELECT COUNT(*) AS MARKETING_SPEND_ROWS FROM MARKETING_SPEND;
SELECT COUNT(*) AS DATE_DIM_ROWS FROM DATE_DIM;

