-- Validate customer relationships
-- Unique keys don't automatically guarantee valid relationships.

-- For example, an order might contain a CUSTOMER_ID that doesn't exist in STG_CUSTOMERS.

-- We need to check for these orphan records before creating foreign-key relationships.


SELECT
    'ORDERS' AS SOURCE_TABLE,
    COUNT(*) AS ORPHAN_RECORDS
FROM CUSTOMER_ANALYTICS.STAGING.STG_ORDERS O
LEFT JOIN CUSTOMER_ANALYTICS.STAGING.STG_CUSTOMERS C
    ON O.CUSTOMER_ID = C.CUSTOMER_ID
WHERE C.CUSTOMER_ID IS NULL

UNION ALL

SELECT
    'SUBSCRIPTIONS',
    COUNT(*)
FROM CUSTOMER_ANALYTICS.STAGING.STG_SUBSCRIPTION_HISTORY S
LEFT JOIN CUSTOMER_ANALYTICS.STAGING.STG_CUSTOMERS C
    ON S.CUSTOMER_ID = C.CUSTOMER_ID
WHERE C.CUSTOMER_ID IS NULL

UNION ALL

SELECT
    'CUSTOMER_FEATURES',
    COUNT(*)
FROM CUSTOMER_ANALYTICS.STAGING.STG_CUSTOMER_FEATURES F
LEFT JOIN CUSTOMER_ANALYTICS.STAGING.STG_CUSTOMERS C
    ON F.CUSTOMER_ID = C.CUSTOMER_ID
WHERE C.CUSTOMER_ID IS NULL

UNION ALL

SELECT
    'CUSTOMER_UNIT_ECONOMICS',
    COUNT(*)
FROM CUSTOMER_ANALYTICS.STAGING.STG_CUSTOMER_UNIT_ECONOMICS E
LEFT JOIN CUSTOMER_ANALYTICS.STAGING.STG_CUSTOMERS C
    ON E.CUSTOMER_ID = C.CUSTOMER_ID
WHERE C.CUSTOMER_ID IS NULL;


-- Validate our date relationships
-- Our DIM_DATE will be important because we'll use it to analyze orders over time, subscription activity and marketing performance.

-- We need to check whether the dates in our fact sources exist in STG_DATE_DIM


SELECT
    'ORDERS' AS SOURCE_TABLE,
    COUNT(*) AS TOTAL_RECORDS,
    COUNT_IF(D.DATE IS NULL) AS MISSING_DATE_KEYS
FROM CUSTOMER_ANALYTICS.STAGING.STG_ORDERS O
LEFT JOIN CUSTOMER_ANALYTICS.STAGING.STG_DATE_DIM D
    ON O.ORDER_DATE = D.DATE

UNION ALL

SELECT
    'SUBSCRIPTION_START',
    COUNT(*),
    COUNT_IF(D.DATE IS NULL)
FROM CUSTOMER_ANALYTICS.STAGING.STG_SUBSCRIPTION_HISTORY S
LEFT JOIN CUSTOMER_ANALYTICS.STAGING.STG_DATE_DIM D
    ON S.START_DATE = D.DATE

UNION ALL

SELECT
    'SUBSCRIPTION_END',
    COUNT(*),
    COUNT_IF(D.DATE IS NULL)
FROM CUSTOMER_ANALYTICS.STAGING.STG_SUBSCRIPTION_HISTORY S
LEFT JOIN CUSTOMER_ANALYTICS.STAGING.STG_DATE_DIM D
    ON S.END_DATE = D.DATE
WHERE S.END_DATE IS NOT NULL

UNION ALL

SELECT
    'MARKETING',
    COUNT(*),
    COUNT_IF(D.DATE IS NULL)
FROM CUSTOMER_ANALYTICS.STAGING.STG_MARKETING_SPEND M
LEFT JOIN CUSTOMER_ANALYTICS.STAGING.STG_DATE_DIM D
    ON M.MONTH = D.DATE;


-- Investigate marketing grain
-- Our marketing table has 960 records. Before designing FACT_MARKETING_SPEND, we need to establish what uniquely identifies each record.

-- A likely grain is:

-- MONTH + CHANNEL + REGION + CAMPAIGN_ID

-- Let's verify it.


SELECT
    COUNT(*) AS TOTAL_ROWS,
    COUNT(DISTINCT CONCAT(
        TO_VARCHAR(MONTH), '|',
        CHANNEL, '|',
        REGION, '|',
        COALESCE(CAMPAIGN_ID, 'NULL')
    )) AS UNIQUE_COMBINATIONS,
    COUNT_IF(CAMPAIGN_ID IS NULL) AS NULL_CAMPAIGN_IDS
FROM CUSTOMER_ANALYTICS.STAGING.STG_MARKETING_SPEND;


-- let's see how many distinct values each dimension has:

SELECT
    COUNT(DISTINCT MONTH) AS UNIQUE_MONTHS,
    COUNT(DISTINCT CHANNEL) AS UNIQUE_CHANNELS,
    COUNT(DISTINCT REGION) AS UNIQUE_REGIONS,
    COUNT(DISTINCT CAMPAIGN_ID) AS UNIQUE_CAMPAIGNS
FROM CUSTOMER_ANALYTICS.STAGING.STG_MARKETING_SPEND;
