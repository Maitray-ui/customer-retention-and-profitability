-- Prerequisite: RAW and STAGING objects must already exist and be populated.
-- Review the accompanying FILE_5_CHANGELOG.md before execution.

-- Purpose: Create and populate the shared dimensions used by the fact tables.
-- Surrogate keys are generated for region, channel, and customer dimensions.

-- create the schema


CREATE SCHEMA IF NOT EXISTS CUSTOMER_ANALYTICS.MODEL;

-- Then create our date dimension:


CREATE OR REPLACE TABLE CUSTOMER_ANALYTICS.MODEL.DIM_DATE AS
SELECT
    DATE AS DATE_KEY,
    DATE,
    DAY,
    WEEK,
    MONTH,
    QUARTER,
    YEAR,
    FISCAL_YEAR
FROM CUSTOMER_ANALYTICS.STAGING.STG_DATE_DIM;



-- Validate DIM_DATE


SELECT
    COUNT(*) AS TOTAL_ROWS,
    COUNT(DISTINCT DATE_KEY) AS UNIQUE_DATE_KEYS,
    MIN(DATE_KEY) AS FIRST_DATE,
    MAX(DATE_KEY) AS LAST_DATE,
    COUNT_IF(DATE_KEY IS NULL) AS NULL_DATE_KEYS
FROM CUSTOMER_ANALYTICS.MODEL.DIM_DATE;



-- DIM_REGION and DIM_CHANNEL
-- Before creating them, there's one thing we should verify: whether the region and channel values in our customer and marketing datasets are consistent.

-- For example, West and WEST might represent the same region but appear as separate values.


-- Check region consistency
SELECT
    'CUSTOMERS' AS SOURCE,
    REGION AS ATTRIBUTE_VALUE,
    COUNT(*) AS RECORD_COUNT
FROM CUSTOMER_ANALYTICS.STAGING.STG_CUSTOMERS
GROUP BY REGION

UNION ALL

SELECT
    'MARKETING',
    REGION,
    COUNT(*)
FROM CUSTOMER_ANALYTICS.STAGING.STG_MARKETING_SPEND
GROUP BY REGION

ORDER BY ATTRIBUTE_VALUE, SOURCE;




-- Check acquisition channel consistency
SELECT
    'CUSTOMERS' AS SOURCE,
    ACQUISITION_CHANNEL AS ATTRIBUTE_VALUE,
    COUNT(*) AS RECORD_COUNT
FROM CUSTOMER_ANALYTICS.STAGING.STG_CUSTOMERS
GROUP BY ACQUISITION_CHANNEL

UNION ALL

SELECT
    'MARKETING',
    CHANNEL,
    COUNT(*)
FROM CUSTOMER_ANALYTICS.STAGING.STG_MARKETING_SPEND
GROUP BY CHANNEL

ORDER BY ATTRIBUTE_VALUE, SOURCE;

-- investigate before creating DIM_REGION


SELECT *
FROM CUSTOMER_ANALYTICS.STAGING.STG_CUSTOMERS
WHERE REGION = 'Tier2'
LIMIT 10;



-- Let's verify the original source


SELECT
    REGION,
    COUNT(*) AS CUSTOMER_COUNT
FROM CUSTOMER_ANALYTICS.RAW.CUSTOMERS
GROUP BY REGION
ORDER BY CUSTOMER_COUNT DESC;

-- Then inspect the marketing source:


SELECT
    REGION,
    COUNT(*) AS RECORD_COUNT
FROM CUSTOMER_ANALYTICS.RAW.MARKETING_SPEND
GROUP BY REGION
ORDER BY REGION;


-- Create DIM_REGION
-- We'll use a surrogate key called REGION_KEY.

-- A surrogate key is an artificial identifier assigned by the warehouse, rather than using the original text value as the key.


-- DIM_REGION is created once below. The original file contained an earlier
-- CREATE/INSERT pair followed by another CREATE OR REPLACE, which reset the
-- table before repopulating it. The redundant first pair is omitted here.


-- Create DIM_REGION separately

CREATE OR REPLACE TABLE CUSTOMER_ANALYTICS.MODEL.DIM_REGION (
    REGION_KEY NUMBER IDENTITY(1,1),
    REGION_NAME VARCHAR(100)
);

-- insert the region values
-- After Step 1 succeeds, execute:

INSERT INTO CUSTOMER_ANALYTICS.MODEL.DIM_REGION (REGION_NAME)
SELECT DISTINCT REGION
FROM CUSTOMER_ANALYTICS.STAGING.STG_CUSTOMERS
WHERE REGION IS NOT NULL
ORDER BY REGION;


-- Verify

SELECT *
FROM CUSTOMER_ANALYTICS.MODEL.DIM_REGION;


-- Create DIM_CHANNEL

CREATE OR REPLACE TABLE CUSTOMER_ANALYTICS.MODEL.DIM_CHANNEL (
    CHANNEL_KEY NUMBER IDENTITY(1,1),
    CHANNEL_NAME VARCHAR(100)
);


-- nsert the distinct channels:

INSERT INTO CUSTOMER_ANALYTICS.MODEL.DIM_CHANNEL (CHANNEL_NAME)
SELECT DISTINCT ACQUISITION_CHANNEL
FROM CUSTOMER_ANALYTICS.STAGING.STG_CUSTOMERS
WHERE ACQUISITION_CHANNEL IS NOT NULL
ORDER BY ACQUISITION_CHANNEL;

-- verify

SELECT *
FROM CUSTOMER_ANALYTICS.MODEL.DIM_CHANNEL
ORDER BY CHANNEL_KEY;


-- One quick validation before creation
-- We need to make sure every customer can map to our region and channel dimensions.



SELECT
    COUNT(*) AS TOTAL_CUSTOMERS,

    COUNT_IF(C.REGION IS NULL) AS NULL_REGIONS,

    COUNT_IF(C.ACQUISITION_CHANNEL IS NULL) AS NULL_CHANNELS,

    COUNT_IF(R.REGION_KEY IS NULL
             AND C.REGION IS NOT NULL) AS UNMAPPED_REGIONS,

    COUNT_IF(CH.CHANNEL_KEY IS NULL
             AND C.ACQUISITION_CHANNEL IS NOT NULL) AS UNMAPPED_CHANNELS

FROM CUSTOMER_ANALYTICS.STAGING.STG_CUSTOMERS C

LEFT JOIN CUSTOMER_ANALYTICS.MODEL.DIM_REGION R
    ON C.REGION = R.REGION_NAME

LEFT JOIN CUSTOMER_ANALYTICS.MODEL.DIM_CHANNEL CH
    ON C.ACQUISITION_CHANNEL = CH.CHANNEL_NAME;



-- Create the customer dimension


CREATE OR REPLACE TABLE CUSTOMER_ANALYTICS.MODEL.DIM_CUSTOMER (
    CUSTOMER_KEY NUMBER IDENTITY(1,1),
    CUSTOMER_ID NUMBER,
    SIGNUP_DATE DATE,
    ACQUISITION_CHANNEL_KEY NUMBER,
    REGION_KEY NUMBER,
    ACQUISITION_MONTH VARCHAR(20),
    ACQUISITION_CAMPAIGN_ID VARCHAR(100),
    DEVICE_TYPE VARCHAR(50),
    FIRST_ORDER_DATE DATE,
    HAS_PLACED_ORDER BOOLEAN,
    CUSTOMER_STATUS VARCHAR(50),
    DATE_OF_BIRTH DATE,
    GENDER VARCHAR(20)
);



-- Populate DIM_CUSTOMER


INSERT INTO CUSTOMER_ANALYTICS.MODEL.DIM_CUSTOMER (
    CUSTOMER_ID,
    SIGNUP_DATE,
    ACQUISITION_CHANNEL_KEY,
    REGION_KEY,
    ACQUISITION_MONTH,
    ACQUISITION_CAMPAIGN_ID,
    DEVICE_TYPE,
    FIRST_ORDER_DATE,
    HAS_PLACED_ORDER,
    CUSTOMER_STATUS,
    DATE_OF_BIRTH,
    GENDER
)

SELECT
    C.CUSTOMER_ID,
    C.SIGNUP_DATE,
    CH.CHANNEL_KEY,
    R.REGION_KEY,
    C.ACQUISITION_MONTH,
    C.ACQUISITION_CAMPAIGN_ID,
    C.DEVICE_TYPE,
    C.FIRST_ORDER_DATE,
    C.HAS_PLACED_ORDER,
    C.CUSTOMER_STATUS,
    C.DATE_OF_BIRTH,
    C.GENDER

FROM CUSTOMER_ANALYTICS.STAGING.STG_CUSTOMERS C

LEFT JOIN CUSTOMER_ANALYTICS.MODEL.DIM_CHANNEL CH
    ON C.ACQUISITION_CHANNEL = CH.CHANNEL_NAME

LEFT JOIN CUSTOMER_ANALYTICS.MODEL.DIM_REGION R
    ON C.REGION = R.REGION_NAME;



-- Validate


SELECT
    COUNT(*) AS TOTAL_ROWS,
    COUNT(DISTINCT CUSTOMER_KEY) AS UNIQUE_CUSTOMER_KEYS,
    COUNT(DISTINCT CUSTOMER_ID) AS UNIQUE_CUSTOMER_IDS,
    COUNT_IF(CUSTOMER_KEY IS NULL) AS NULL_SURROGATE_KEYS,
    COUNT_IF(ACQUISITION_CHANNEL_KEY IS NULL) AS NULL_CHANNEL_KEYS,
    COUNT_IF(REGION_KEY IS NULL) AS NULL_REGION_KEYS
FROM CUSTOMER_ANALYTICS.MODEL.DIM_CUSTOMER;
