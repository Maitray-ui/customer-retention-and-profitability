-- Customer Retention & Profitability
-- Dimensional model build and validation
-- Database: CUSTOMER_ANALYTICS
-- Schema: MODEL
--
-- Execute in this order:
--   01_model_source_validation.sql
--   02_create_dimension_tables.sql
--   03_create_fact_tables.sql
--   04_validate_model_relationships.sql
--
-- Prerequisite: RAW and STAGING objects must already exist and be populated.
-- Review the accompanying FILE_5_CHANGELOG.md before execution.

-- Purpose: Build the fact tables at the grains represented by their staging sources.
-- Each fact table resolves customer, date, region, and channel references to dimension keys
-- where those joins are present in the original model.

-- Build FACT_ORDERS
-- Create FACT_ORDERS


CREATE OR REPLACE TABLE CUSTOMER_ANALYTICS.MODEL.FACT_ORDERS AS

SELECT
    O.ORDER_ID,
    C.CUSTOMER_KEY,
    O.ORDER_DATE AS ORDER_DATE_KEY,
    O.PRODUCT_CATEGORY,
    O.QUANTITY,
    O.REVENUE,
    O.DISCOUNT,
    O.COST_OF_GOODS,
    O.SHIPPING_COST,
    O.DELIVERY_REGION_COST,
    O.PAYMENT_PROCESSING_FEE,
    O.ORDER_STATUS,
    O.IS_COMPLETED_ORDER,
    O.IS_RETURNED_ORDER,
    O.REFUND_AMOUNT,
    O.NET_REVENUE,
    O.GROSS_MARGIN,
    O.ADJUSTED_CONTRIBUTION

FROM CUSTOMER_ANALYTICS.STAGING.STG_ORDERS O

LEFT JOIN CUSTOMER_ANALYTICS.MODEL.DIM_CUSTOMER C
    ON O.CUSTOMER_ID = C.CUSTOMER_ID;



-- Validate FACT_ORDERS


SELECT
    COUNT(*) AS TOTAL_ROWS,
    COUNT(DISTINCT ORDER_ID) AS UNIQUE_ORDER_IDS,
    COUNT_IF(CUSTOMER_KEY IS NULL) AS NULL_CUSTOMER_KEYS,
    COUNT_IF(ORDER_DATE_KEY IS NULL) AS NULL_DATE_KEYS
FROM CUSTOMER_ANALYTICS.MODEL.FACT_ORDERS;



-- FACT_SUBSCRIPTIONS


CREATE OR REPLACE TABLE CUSTOMER_ANALYTICS.MODEL.FACT_SUBSCRIPTIONS AS

SELECT
    S.SUBSCRIPTION_ID,
    C.CUSTOMER_KEY,

    S.START_DATE AS START_DATE_KEY,
    S.END_DATE AS END_DATE_KEY,

    S.SUBSCRIPTION_TIER,
    S.MONTHLY_FEE,
    S.CHURN_FLAG,
    S.IS_CHURNED,
    S.CHURN_REASON,
    S.REACTIVATION_FLAG,
    S.IS_REACTIVATED,
    S.SUBSCRIPTION_DURATION_DAYS

FROM CUSTOMER_ANALYTICS.STAGING.STG_SUBSCRIPTION_HISTORY S

LEFT JOIN CUSTOMER_ANALYTICS.MODEL.DIM_CUSTOMER C
    ON S.CUSTOMER_ID = C.CUSTOMER_ID;



-- Validate the fact table


SELECT
    COUNT(*) AS TOTAL_ROWS,
    COUNT(DISTINCT SUBSCRIPTION_ID) AS UNIQUE_SUBSCRIPTION_IDS,
    COUNT_IF(CUSTOMER_KEY IS NULL) AS NULL_CUSTOMER_KEYS,
    COUNT_IF(START_DATE_KEY IS NULL) AS NULL_START_DATES,
    COUNT_IF(END_DATE_KEY IS NULL) AS NULL_END_DATES
FROM CUSTOMER_ANALYTICS.MODEL.FACT_SUBSCRIPTIONS;



-- FACT_MARKETING_SPEND
-- Create FACT_MARKETING_SPEND


CREATE OR REPLACE TABLE CUSTOMER_ANALYTICS.MODEL.FACT_MARKETING_SPEND AS

SELECT
    M.CAMPAIGN_ID,

    M.MONTH AS MONTH_DATE_KEY,
    R.REGION_KEY,
    CH.CHANNEL_KEY,

    M.SPEND_AMOUNT,
    M.IMPRESSIONS,
    M.CLICKS,
    M.CONVERSIONS,
    M.NEW_CUSTOMERS,

    M.CTR,
    M.CONVERSION_RATE,
    M.MARKETING_COST_PER_NEW_CUSTOMER

FROM CUSTOMER_ANALYTICS.STAGING.STG_MARKETING_SPEND M

LEFT JOIN CUSTOMER_ANALYTICS.MODEL.DIM_REGION R
    ON M.REGION = R.REGION_NAME

LEFT JOIN CUSTOMER_ANALYTICS.MODEL.DIM_CHANNEL CH
    ON M.CHANNEL = CH.CHANNEL_NAME;


-- Validate


SELECT
    COUNT(*) AS TOTAL_ROWS,
    COUNT(DISTINCT CAMPAIGN_ID) AS UNIQUE_CAMPAIGNS,

    COUNT_IF(MONTH_DATE_KEY IS NULL) AS NULL_DATE_KEYS,
    COUNT_IF(REGION_KEY IS NULL) AS NULL_REGION_KEYS,
    COUNT_IF(CHANNEL_KEY IS NULL) AS NULL_CHANNEL_KEYS

FROM CUSTOMER_ANALYTICS.MODEL.FACT_MARKETING_SPEND;



-- FACT_CUSTOMER_ECONOMICS
-- Create FACT_CUSTOMER_ECONOMICS


CREATE OR REPLACE TABLE CUSTOMER_ANALYTICS.MODEL.FACT_CUSTOMER_ECONOMICS AS

SELECT
    C.CUSTOMER_KEY,

    E.TOTAL_REVENUE,
    E.TOTAL_DISCOUNT,
    E.TOTAL_COGS,
    E.TOTAL_SHIPPING,
    E.TOTAL_REFUNDS,
    E.CAC,
    E.CONTRIBUTION_MARGIN,
    E.LTV,
    E.PAYBACK_MONTHS,
    E.HAS_POSITIVE_CONTRIBUTION,
    E.PAYBACK_STATUS

FROM CUSTOMER_ANALYTICS.STAGING.STG_CUSTOMER_UNIT_ECONOMICS E

LEFT JOIN CUSTOMER_ANALYTICS.MODEL.DIM_CUSTOMER C
    ON E.CUSTOMER_ID = C.CUSTOMER_ID;


-- Validate


SELECT
    COUNT(*) AS TOTAL_ROWS,
    COUNT(DISTINCT CUSTOMER_KEY) AS UNIQUE_CUSTOMERS,
    COUNT_IF(CUSTOMER_KEY IS NULL) AS NULL_CUSTOMER_KEYS
FROM CUSTOMER_ANALYTICS.MODEL.FACT_CUSTOMER_ECONOMICS;



-- Create FACT_CUSTOMER_FEATURES


CREATE OR REPLACE TABLE CUSTOMER_ANALYTICS.MODEL.FACT_CUSTOMER_FEATURES AS

SELECT
    C.CUSTOMER_KEY,

    F.ORDER_FREQUENCY,
    F.AVG_ORDER_VALUE,
    F.AVG_DISCOUNT_RATE,
    F.DAYS_SINCE_LAST_ORDER,
    F.AVG_INTERPURCHASE_TIME,
    F.SUBSCRIPTION_TENURE,
    F.DISCOUNT_DEPENDENCY_RATIO,
    F.HAS_PURCHASED,
    F.IS_HIGH_DISCOUNT_DEPENDENT

FROM CUSTOMER_ANALYTICS.STAGING.STG_CUSTOMER_FEATURES F

LEFT JOIN CUSTOMER_ANALYTICS.MODEL.DIM_CUSTOMER C
    ON F.CUSTOMER_ID = C.CUSTOMER_ID;


-- Validate


SELECT
    COUNT(*) AS TOTAL_ROWS,
    COUNT(DISTINCT CUSTOMER_KEY) AS UNIQUE_CUSTOMERS,
    COUNT_IF(CUSTOMER_KEY IS NULL) AS NULL_CUSTOMER_KEYS
FROM CUSTOMER_ANALYTICS.MODEL.FACT_CUSTOMER_FEATURES;
