-- Purpose: Inspect the completed MODEL schema and validate dimension/fact relationships.
-- These checks report unmatched references; they do not enforce database constraints.

-- First, let's inspect the completed MODEL schema


SELECT
    TABLE_NAME,
    TABLE_TYPE
FROM CUSTOMER_ANALYTICS.INFORMATION_SCHEMA.TABLES
WHERE TABLE_SCHEMA = 'MODEL'
ORDER BY TABLE_TYPE, TABLE_NAME;


-- Final relationship validation
-- We've already checked individual keys and several relationships. Now let's perform a consolidated check to ensure every fact-table reference resolves to its intended dimension.


-- 1. Customer dimension relationships
SELECT
    'DIM_CUSTOMER -> DIM_REGION' AS RELATIONSHIP,
    COUNT(*) AS TOTAL_RECORDS,
    COUNT_IF(R.REGION_KEY IS NULL) AS UNMATCHED_RECORDS
FROM CUSTOMER_ANALYTICS.MODEL.DIM_CUSTOMER C
LEFT JOIN CUSTOMER_ANALYTICS.MODEL.DIM_REGION R
    ON C.REGION_KEY = R.REGION_KEY

UNION ALL

SELECT
    'DIM_CUSTOMER -> DIM_CHANNEL',
    COUNT(*),
    COUNT_IF(CH.CHANNEL_KEY IS NULL)
FROM CUSTOMER_ANALYTICS.MODEL.DIM_CUSTOMER C
LEFT JOIN CUSTOMER_ANALYTICS.MODEL.DIM_CHANNEL CH
    ON C.ACQUISITION_CHANNEL_KEY = CH.CHANNEL_KEY

UNION ALL

-- 2. Orders relationships
SELECT
    'FACT_ORDERS -> DIM_CUSTOMER',
    COUNT(*),
    COUNT_IF(C.CUSTOMER_KEY IS NULL)
FROM CUSTOMER_ANALYTICS.MODEL.FACT_ORDERS F
LEFT JOIN CUSTOMER_ANALYTICS.MODEL.DIM_CUSTOMER C
    ON F.CUSTOMER_KEY = C.CUSTOMER_KEY

UNION ALL

SELECT
    'FACT_ORDERS -> DIM_DATE',
    COUNT(*),
    COUNT_IF(D.DATE_KEY IS NULL)
FROM CUSTOMER_ANALYTICS.MODEL.FACT_ORDERS F
LEFT JOIN CUSTOMER_ANALYTICS.MODEL.DIM_DATE D
    ON F.ORDER_DATE_KEY = D.DATE_KEY

UNION ALL

-- 3. Subscription relationships
SELECT
    'FACT_SUBSCRIPTIONS -> DIM_CUSTOMER',
    COUNT(*),
    COUNT_IF(C.CUSTOMER_KEY IS NULL)
FROM CUSTOMER_ANALYTICS.MODEL.FACT_SUBSCRIPTIONS F
LEFT JOIN CUSTOMER_ANALYTICS.MODEL.DIM_CUSTOMER C
    ON F.CUSTOMER_KEY = C.CUSTOMER_KEY

UNION ALL

SELECT
    'FACT_SUBSCRIPTIONS -> DIM_DATE (START)',
    COUNT(*),
    COUNT_IF(D.DATE_KEY IS NULL)
FROM CUSTOMER_ANALYTICS.MODEL.FACT_SUBSCRIPTIONS F
LEFT JOIN CUSTOMER_ANALYTICS.MODEL.DIM_DATE D
    ON F.START_DATE_KEY = D.DATE_KEY

UNION ALL

SELECT
    'FACT_SUBSCRIPTIONS -> DIM_DATE (END)',
    COUNT(*),
    COUNT_IF(D.DATE_KEY IS NULL)
FROM CUSTOMER_ANALYTICS.MODEL.FACT_SUBSCRIPTIONS F
LEFT JOIN CUSTOMER_ANALYTICS.MODEL.DIM_DATE D
    ON F.END_DATE_KEY = D.DATE_KEY

UNION ALL

-- 4. Marketing relationships
SELECT
    'FACT_MARKETING_SPEND -> DIM_DATE',
    COUNT(*),
    COUNT_IF(D.DATE_KEY IS NULL)
FROM CUSTOMER_ANALYTICS.MODEL.FACT_MARKETING_SPEND F
LEFT JOIN CUSTOMER_ANALYTICS.MODEL.DIM_DATE D
    ON F.MONTH_DATE_KEY = D.DATE_KEY

UNION ALL

SELECT
    'FACT_MARKETING_SPEND -> DIM_REGION',
    COUNT(*),
    COUNT_IF(R.REGION_KEY IS NULL)
FROM CUSTOMER_ANALYTICS.MODEL.FACT_MARKETING_SPEND F
LEFT JOIN CUSTOMER_ANALYTICS.MODEL.DIM_REGION R
    ON F.REGION_KEY = R.REGION_KEY

UNION ALL

SELECT
    'FACT_MARKETING_SPEND -> DIM_CHANNEL',
    COUNT(*),
    COUNT_IF(CH.CHANNEL_KEY IS NULL)
FROM CUSTOMER_ANALYTICS.MODEL.FACT_MARKETING_SPEND F
LEFT JOIN CUSTOMER_ANALYTICS.MODEL.DIM_CHANNEL CH
    ON F.CHANNEL_KEY = CH.CHANNEL_KEY

UNION ALL

-- 5. Customer-level fact relationships
